/**
 * Basic Pipeline — dynamic GitHub Actions workflow generator.
 *
 * Composes test + deploy jobs based on:
 *   projectType     — what language / framework is being used
 *   iac             — what infrastructure tool will be deployed
 *   projectTypeConfig — version + database choices
 */

function generate({ projectName, appName, projectType, iac, infra, projectTypeConfig }) {
  const ptId   = projectType?.id ?? null;
  const iacId  = iac?.id         ?? 'none';
  const infraId= infra?.id       ?? 'none';
  const cfg    = projectTypeConfig ?? {};

  // ── Project-type flags ──────────────────────────────────────────────────
  const isDjango      = ptId === 'django-api';
  const isFastApi     = ptId === 'fastapi';
  const isLambdaPy    = ptId === 'python-lambda';
  const isServerless  = ptId === 'serverless';
  const isPythonApp   = isDjango || isFastApi;
  const isPython      = isPythonApp || isLambdaPy || isServerless;
  const isJava        = ptId === 'java-spring' || ptId === 'java-lambda';
  const isMfe         = ptId === 'react-mfe' || ptId === 'react-shell';
  const isNodeApi     = ptId === 'nodejs-api';
  const isNodeLambda  = ptId === 'nodejs-lambda';
  const isNode        = isMfe || isNodeApi || isNodeLambda;
  const isDotnet      = ptId === 'dotnet-api';

  // ── IaC flags ───────────────────────────────────────────────────────────
  const hasPyCdk    = iacId === 'python-cdk';
  const hasTsCdk    = iacId === 'typescript-cdk';
  const hasCdk      = hasPyCdk || hasTsCdk || iacId === 'csharp-cdk';
  const hasTf       = iacId === 'terraform';
  const hasSam      = iacId === 'sam';

  // ── Infra architecture flags ─────────────────────────────────────────────
  const isEcs         = infraId === 'ecs-fargate' || infraId === 'ecs-ec2';
  const isEks         = infraId === 'eks';
  const isLambdaInfra = infraId === 'lambda';
  const isS3Cf        = infraId === 's3-cloudfront';
  const needsDocker   = isEcs || isEks;

  // ── Config values ───────────────────────────────────────────────────────
  const pythonVer  = cfg.pythonVersion  ?? '3.14';
  const javaVer    = cfg.javaVersion    ?? '21';
  const nodeVer    = cfg.nodeVersion    ?? '26';
  const dotnetVer  = cfg.dotnetVersion  ?? '8.0';
  const database   = cfg.database       ?? 'postgresql';

  const needsPostgres = isPythonApp && database === 'postgresql';

  const parts = [];

  // ── Header ──────────────────────────────────────────────────────────────
  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# GitHub Actions — ${projectName}
# Generated by the DevOps Self-Service Portal
#
# Project type : ${projectType?.name  ?? 'None'}
# IaC          : ${iac && iacId !== 'none' ? iac.name : 'None'}
# ──────────────────────────────────────────────────────────────────────────────

name: CI/CD Pipeline

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

env:
  AWS_REGION: \${{ vars.AWS_REGION || 'eu-west-2' }}${needsDocker ? `
  ECR_REPOSITORY: ${appName}` : ''}`
  );

  // ══════════════════════════════════════════════════════════════════════════
  // JOBS
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`\njobs:`);

  // ── Python Test Job ─────────────────────────────────────────────────────
  if (isPython) {
    const services = needsPostgres
      ? `
    services:
      postgres:
        image: postgres:16-alpine
        env:
          POSTGRES_DB: ${appName}_test
          POSTGRES_USER: postgres
          POSTGRES_PASSWORD: postgres
        ports:
          - 5432:5432
        options: >-
          --health-cmd pg_isready
          --health-interval 10s
          --health-timeout 5s
          --health-retries 5`
      : '';

    parts.push(
`  test:
    name: Test
    runs-on: ubuntu-latest${services}
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'
          cache: 'pip'

      - name: Install dependencies
        run: pip install -r requirements.txt

      - name: Lint with Ruff
        run: |
          pip install ruff
          ruff check .

      - name: Run tests
        run: pytest --cov=. --cov-report=xml -v${needsPostgres ? `
        env:
          DATABASE_URL: postgres://postgres:postgres@localhost:5432/${appName}_test` : ''}`
    );
  }

  // ── Java Test Job ───────────────────────────────────────────────────────
  if (isJava) {
    parts.push(
`  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up JDK
        uses: actions/setup-java@v4
        with:
          java-version: '${javaVer}'
          distribution: 'temurin'
          cache: 'maven'

      - name: Run tests
        run: mvn test -q`
    );
  }

  // ── Node Test Job ───────────────────────────────────────────────────────
  if (isNode) {
    parts.push(
`  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '${nodeVer}'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      - name: Lint
        run: npm run lint

      - name: Run tests
        run: npm test`
    );
  }

  // ── .NET Test Job ───────────────────────────────────────────────────────
  if (isDotnet) {
    parts.push(
`  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up .NET
        uses: actions/setup-dotnet@v4
        with:
          dotnet-version: '${dotnetVer}'

      - name: Restore dependencies
        run: dotnet restore

      - name: Run tests
        run: dotnet test --no-restore --verbosity minimal`
    );
  }

  // ── Docker Build Job ────────────────────────────────────────────────────
  if (needsDocker) {
    parts.push(
`
  build:
    name: Build & Push Docker Image
    runs-on: ubuntu-latest
    needs: test
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    outputs:
      image-tag: \${{ steps.build.outputs.image-tag }}
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Login to Amazon ECR
        id: login-ecr
        uses: aws-actions/amazon-ecr-login@v2

      - name: Build and push Docker image
        id: build
        env:
          ECR_REGISTRY: \${{ steps.login-ecr.outputs.registry }}
          IMAGE_TAG: \${{ github.sha }}
        run: |
          docker build -t $ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG .
          docker push $ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG
          echo "image-tag=$IMAGE_TAG" >> $GITHUB_OUTPUT`
    );
  }

  // ── S3 + CloudFront Deploy ──────────────────────────────────────────────
  if (isS3Cf && isNode) {
    parts.push(
`
  build:
    name: Build
    runs-on: ubuntu-latest
    needs: test
    steps:
      - uses: actions/checkout@v4

      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '${nodeVer}'
          cache: 'npm'

      - name: Install and build
        run: |
          npm ci
          npm run build

      - name: Upload artifact
        uses: actions/upload-artifact@v4
        with:
          name: dist
          path: dist/

  deploy:
    name: Deploy to S3
    runs-on: ubuntu-latest
    needs: build
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - name: Download artifact
        uses: actions/download-artifact@v4
        with:
          name: dist
          path: dist/

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy to S3
        run: aws s3 sync dist/ s3://\${{ vars.S3_BUCKET }} --delete

      - name: Invalidate CloudFront
        run: |
          aws cloudfront create-invalidation \\
            --distribution-id \${{ vars.CLOUDFRONT_DISTRIBUTION_ID }} \\
            --paths "/*"`
    );
  }

  // ── CDK Deploy ──────────────────────────────────────────────────────────
  if (hasCdk) {
    const cdkSetup = hasTsCdk
      ? `      - name: Install CDK
        run: |
          cd devops/cdk
          npm ci
          npm install -g aws-cdk`
      : `      - name: Install CDK
        run: |
          pip install -r devops/cdk/requirements.txt
          npm install -g aws-cdk`;

    const needsJob = needsDocker ? 'build' : 'test';

    parts.push(
`
  deploy:
    name: Deploy Infrastructure
    runs-on: ubuntu-latest
    needs: ${needsJob}
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - uses: actions/checkout@v4
${hasTsCdk ? '' : `
      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'
`}
      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '20'

${cdkSetup}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: CDK Deploy
        run: |
          cd devops/cdk
          cdk deploy --require-approval never${needsDocker ? ' --context imageTag=${{ needs.build.outputs.image-tag }}' : ''}`
    );
  }

  // ── Terraform Deploy ────────────────────────────────────────────────────
  if (hasTf) {
    parts.push(
`
  terraform:
    name: Terraform
    runs-on: ubuntu-latest
    needs: test
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment: production
    defaults:
      run:
        working-directory: devops/terraform
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9

      - name: Terraform Init
        run: terraform init

      - name: Terraform Plan
        run: terraform plan -out=tfplan

      - name: Terraform Apply
        run: terraform apply -auto-approve tfplan`
    );
  }

  // ── SAM Deploy ──────────────────────────────────────────────────────────
  if (hasSam) {
    parts.push(
`
  deploy:
    name: Deploy SAM Application
    runs-on: ubuntu-latest
    needs: test
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Setup SAM CLI
        uses: aws-actions/setup-sam@v2

      - name: SAM Build
        run: sam build

      - name: SAM Deploy
        run: |
          sam deploy \\
            --no-confirm-changeset \\
            --no-fail-on-empty-changeset \\
            --stack-name ${projectName} \\
            --capabilities CAPABILITY_IAM`
    );
  }

  // ── ECS Deploy (when no CDK) ────────────────────────────────────────────
  if (isEcs && !hasCdk && !hasTf) {
    parts.push(
`
  deploy:
    name: Deploy to ECS
    runs-on: ubuntu-latest
    needs: build
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy to ECS
        run: |
          aws ecs update-service \\
            --cluster \${{ vars.ECS_CLUSTER }} \\
            --service \${{ vars.ECS_SERVICE }} \\
            --force-new-deployment

      - name: Wait for deployment
        run: |
          aws ecs wait services-stable \\
            --cluster \${{ vars.ECS_CLUSTER }} \\
            --services \${{ vars.ECS_SERVICE }}`
    );
  }

  // ── Lambda Deploy (when no CDK/SAM) ─────────────────────────────────────
  if (isLambdaInfra && !hasCdk && !hasSam && !hasTf) {
    const pkgCmd = isPython
      ? `          pip install -r requirements.txt -t ./package/
          cp -r *.py ./package/
          cd package && zip -r ../function.zip . && cd ..`
      : isNode
      ? `          npm ci
          zip -r function.zip . -x "*.git*"`
      : `          mvn package -DskipTests -q
          cp target/*.jar function.zip`;

    parts.push(
`
  deploy:
    name: Deploy to Lambda
    runs-on: ubuntu-latest
    needs: test
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - uses: actions/checkout@v4

      - name: Package Lambda
        run: |
${pkgCmd}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy Lambda
        run: |
          aws lambda update-function-code \\
            --function-name \${{ vars.LAMBDA_FUNCTION_NAME }} \\
            --zip-file fileb://function.zip`
    );
  }

  return parts.join('\n');
}

// ─────────────────────────────────────────────────────────────────────────────
// Public API
// ─────────────────────────────────────────────────────────────────────────────

export function buildBasicPipelineFiles(vars) {
  const content = generate(vars);
  return [{ path: '.github/workflows/ci.yml', content }];
}

