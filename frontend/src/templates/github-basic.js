/**
 * Basic Pipeline — dynamic GitHub Actions workflow generator.
 *
 * Full pipeline with staging/production environments, rollbacks, and load testing.
 *
 * Composes test + deploy jobs based on:
 *   projectType     — what language / framework is being used
 *   iac             — what infrastructure tool will be deployed
 *   projectTypeConfig — version + database choices
 *   features        — additional features to inject
 */

import {
  parseFeatureFlags,
  githubSecurityJobs,
  githubSlackJob,
  featureRequirementsComment,
} from './feature-snippets.js';

function generate({ projectName, appName, projectType, iac, infra, projectTypeConfig, features = [] }) {
  const ptId   = projectType?.id ?? null;
  const iacId  = iac?.id         ?? 'none';
  const infraId= infra?.id       ?? 'none';
  const cfg    = projectTypeConfig ?? {};

  // ── Project-type flags ──────────────────────────────────────────────────
  const isDjango      = ptId === 'django-api';
  const isFastApi     = ptId === 'fastapi';
  const isLambdaPy    = ptId === 'python-lambda';
  const isServerless  = ptId === 'serverless';
  const isApiGateway  = ptId === 'api-gateway';
  const isCdkStack    = ptId === 'cdk-stack';
  const isPythonApp   = isDjango || isFastApi;
  const isPython      = isPythonApp || isLambdaPy || isServerless || isApiGateway;
  const isJava        = ptId === 'java-spring' || ptId === 'java-lambda';
  const isMfe         = ptId === 'react-mfe' || ptId === 'react-shell';
  const isNodeApi     = ptId === 'nodejs-api';
  const isNodeLambda  = ptId === 'nodejs-lambda';
  const isNode        = isMfe || isNodeApi || isNodeLambda || isCdkStack;
  const isDotnet      = ptId === 'dotnet-api';

  // ── IaC flags ───────────────────────────────────────────────────────────
  const hasPyCdk    = iacId === 'python-cdk';
  const hasTsCdk    = iacId === 'typescript-cdk';
  const hasCsharpCdk= iacId === 'csharp-cdk';
  const hasCdk      = hasPyCdk || hasTsCdk || hasCsharpCdk || isCdkStack;
  const hasTf       = iacId === 'terraform';
  const hasSam      = iacId === 'sam';
  const hasCfn      = iacId === 'cloudformation';
  const hasPulumiPy = iacId === 'pulumi-python';
  const hasPulumiTs = iacId === 'pulumi-ts';
  const hasIac      = iacId !== 'none';

  // ── Infra architecture flags ─────────────────────────────────────────────
  const isEcsFargate  = infraId === 'ecs-fargate';
  const isEcsEc2      = infraId === 'ecs-ec2';
  const isEcs         = isEcsFargate || isEcsEc2;
  const isEks         = infraId === 'eks';
  const isLambdaInfra = infraId === 'lambda';
  const isS3Cf        = infraId === 's3-cloudfront';
  const isEc2         = infraId === 'ec2';
  const needsDocker   = isEcs || isEks;
  const hasInfraArch  = infraId !== 'none';

  // ── Feature flags ─────────────────────────────────────────────────────────
  const feat = parseFeatureFlags(features, needsDocker);

  // ── Config values ───────────────────────────────────────────────────────
  const pythonVer  = cfg.pythonVersion  ?? '3.14';
  const javaVer    = cfg.javaVersion    ?? '21';
  const nodeVer    = cfg.nodeVersion    ?? '26';
  const dotnetVer  = cfg.dotnetVersion  ?? '8.0';
  const database   = cfg.database       ?? 'postgresql';

  const needsPostgres = isPythonApp && database === 'postgresql';
  const needsMysql    = isPythonApp && database === 'mysql';

  const parts = [];

  // ── Header ──────────────────────────────────────────────────────────────
  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# GitHub Actions — ${projectName}
# Generated by the DevOps Self-Service Portal
#
# Project type : ${projectType?.name  ?? 'None'}
# IaC          : ${iac && iacId !== 'none' ? iac.name : 'None'}
# Infra        : ${infra && infraId !== 'none' ? infra.name : 'None'}
#
# Required secrets:
#   AWS_ROLE_ARN          — IAM role ARN for OIDC authentication
#
# Required variables (Settings → Secrets and variables → Variables):
#   AWS_REGION            — e.g. eu-west-2
#   AWS_ACCOUNT_ID        — AWS account ID${needsDocker ? `
#   ECR_REPOSITORY        — ECR repository name` : ''}${isEcs ? `
#   ECS_CLUSTER_STAGING   — ECS cluster name for staging
#   ECS_SERVICE_STAGING   — ECS service name for staging
#   ECS_CLUSTER_PROD      — ECS cluster name for production
#   ECS_SERVICE_PROD      — ECS service name for production` : ''}${isS3Cf ? `
#   S3_BUCKET_STAGING     — S3 bucket for staging
#   S3_BUCKET_PROD        — S3 bucket for production
#   CLOUDFRONT_DIST_STAGING — CloudFront distribution ID for staging
#   CLOUDFRONT_DIST_PROD  — CloudFront distribution ID for production` : ''}
# ──────────────────────────────────────────────────────────────────────────────

name: CI/CD Pipeline

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

concurrency:
  group: \${{ github.workflow }}-\${{ github.ref }}
  cancel-in-progress: true

env:
  AWS_REGION: \${{ vars.AWS_REGION || 'eu-west-2' }}${needsDocker ? `
  ECR_REPOSITORY: \${{ vars.ECR_REPOSITORY || '${appName}' }}` : ''}${hasCdk ? `
  CDK_DIR: devops/cdk` : ''}${hasTf ? `
  TF_DIR: devops/terraform` : ''}`
  );

  // ══════════════════════════════════════════════════════════════════════════
  // JOBS
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`
jobs:`);

  // ══════════════════════════════════════════════════════════════════════════
  // TEST JOB
  // ══════════════════════════════════════════════════════════════════════════

  // ── Python Test Job ─────────────────────────────────────────────────────
  if (isPython) {
    const services = needsPostgres
      ? `
    services:
      postgres:
        image: postgres:16-alpine
        env:
          POSTGRES_DB: ${appName}_test
          POSTGRES_USER: postgres
          POSTGRES_PASSWORD: postgres
        ports:
          - 5432:5432
        options: >-
          --health-cmd pg_isready
          --health-interval 10s
          --health-timeout 5s
          --health-retries 5`
      : needsMysql
      ? `
    services:
      mysql:
        image: mysql:8.0
        env:
          MYSQL_DATABASE: ${appName}_test
          MYSQL_ROOT_PASSWORD: root
        ports:
          - 3306:3306
        options: >-
          --health-cmd "mysqladmin ping"
          --health-interval 10s
          --health-timeout 5s
          --health-retries 5`
      : '';

    parts.push(
`  # ════════════════════════════════════════════════════════════════════════════
  # TEST
  # ════════════════════════════════════════════════════════════════════════════

  test:
    name: Test
    runs-on: ubuntu-latest${services}
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'
          cache: 'pip'

      - name: Install dependencies
        run: pip install -r requirements.txt

      - name: Lint with Ruff
        run: |
          pip install ruff
          ruff check .

      - name: Run tests
        run: |
          pip install pytest pytest-cov
          pytest --cov=. --cov-report=xml --cov-report=term -v${needsPostgres ? `
        env:
          DATABASE_URL: postgres://postgres:postgres@localhost:5432/${appName}_test` : ''}${needsMysql ? `
        env:
          DATABASE_URL: mysql+pymysql://root:root@localhost:3306/${appName}_test` : ''}

      - name: Upload coverage
        uses: codecov/codecov-action@v4
        with:
          files: coverage.xml
          fail_ci_if_error: false`
    );
  }

  // ── Java Test Job ───────────────────────────────────────────────────────
  if (isJava) {
    parts.push(
`  # ════════════════════════════════════════════════════════════════════════════
  # TEST
  # ════════════════════════════════════════════════════════════════════════════

  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up JDK
        uses: actions/setup-java@v4
        with:
          java-version: '${javaVer}'
          distribution: 'temurin'
          cache: 'maven'

      - name: Run tests
        run: mvn test -q

      - name: Upload test results
        uses: actions/upload-artifact@v4
        if: always()
        with:
          name: test-results
          path: target/surefire-reports/`
    );
  }

  // ── Node Test Job ───────────────────────────────────────────────────────
  if (isNode) {
    parts.push(
`  # ════════════════════════════════════════════════════════════════════════════
  # TEST
  # ════════════════════════════════════════════════════════════════════════════

  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '${nodeVer}'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      - name: Lint
        run: npm run lint

      - name: Run tests
        run: npm test -- --coverage

      - name: Upload coverage
        uses: codecov/codecov-action@v4
        with:
          fail_ci_if_error: false`
    );
  }

  // ── .NET Test Job ───────────────────────────────────────────────────────
  if (isDotnet) {
    parts.push(
`  # ════════════════════════════════════════════════════════════════════════════
  # TEST
  # ════════════════════════════════════════════════════════════════════════════

  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up .NET
        uses: actions/setup-dotnet@v4
        with:
          dotnet-version: '${dotnetVer}'

      - name: Restore dependencies
        run: dotnet restore

      - name: Run tests
        run: dotnet test --no-restore --verbosity minimal --collect:"XPlat Code Coverage"

      - name: Upload coverage
        uses: codecov/codecov-action@v4
        with:
          fail_ci_if_error: false`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // BUILD JOB (Docker for container architectures)
  // ══════════════════════════════════════════════════════════════════════════

  if (needsDocker) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # BUILD
  # ════════════════════════════════════════════════════════════════════════════

  build:
    name: Build & Push Docker Image
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    outputs:
      image-tag: \${{ steps.build.outputs.image-tag }}
      ecr-uri: \${{ steps.build.outputs.ecr-uri }}
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Login to Amazon ECR
        id: login-ecr
        uses: aws-actions/amazon-ecr-login@v2

      - name: Create ECR repository if not exists
        run: |
          aws ecr describe-repositories --repository-names \${{ env.ECR_REPOSITORY }} 2>/dev/null || \\
          aws ecr create-repository --repository-name \${{ env.ECR_REPOSITORY }}

      - name: Build and push Docker image
        id: build
        env:
          ECR_REGISTRY: \${{ steps.login-ecr.outputs.registry }}
          IMAGE_TAG: \${{ github.sha }}
        run: |
          docker build -t $ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG .
          docker push $ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG
          echo "image-tag=$IMAGE_TAG" >> $GITHUB_OUTPUT
          echo "ecr-uri=$ECR_REGISTRY/$ECR_REPOSITORY" >> $GITHUB_OUTPUT`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // BUILD JOB (Static site for S3+CloudFront)
  // ══════════════════════════════════════════════════════════════════════════

  if (isS3Cf && isNode) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # BUILD
  # ════════════════════════════════════════════════════════════════════════════

  build:
    name: Build
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    steps:
      - uses: actions/checkout@v4

      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '${nodeVer}'
          cache: 'npm'

      - name: Install and build
        run: |
          npm ci
          npm run build

      - name: Upload artifact
        uses: actions/upload-artifact@v4
        with:
          name: dist
          path: dist/
          retention-days: 7`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // CDK PIPELINE — Full staging/production flow
  // ══════════════════════════════════════════════════════════════════════════

  if (hasCdk) {
    const cdkSetupSteps = hasTsCdk
      ? `      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'
          cache-dependency-path: \${{ env.CDK_DIR }}/package-lock.json

      - name: Install CDK dependencies
        run: |
          cd \$CDK_DIR
          npm ci
          npm install -g aws-cdk`
      : `      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'
          cache: 'pip'
          cache-dependency-path: \${{ env.CDK_DIR }}/requirements.txt

      - name: Set up Node.js (for CDK CLI)
        uses: actions/setup-node@v4
        with:
          node-version: '20'

      - name: Install CDK dependencies
        run: |
          pip install -r \$CDK_DIR/requirements.txt
          npm install -g aws-cdk`;

    const buildNeeds = needsDocker ? 'build' : 'test';

    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # VALIDATE — CDK Synth
  # ════════════════════════════════════════════════════════════════════════════

  cdk-synth:
    name: CDK Synth
    runs-on: ubuntu-latest
    needs: test
    permissions:
      id-token: write
      contents: read
    steps:
      - uses: actions/checkout@v4

${cdkSetupSteps}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: CDK Synth
        run: cd \$CDK_DIR && cdk synth

  # ════════════════════════════════════════════════════════════════════════════
  # DEPLOY STAGING
  # ════════════════════════════════════════════════════════════════════════════

  deploy-staging:
    name: Deploy to Staging
    runs-on: ubuntu-latest
    needs: [cdk-synth${needsDocker ? ', build' : ''}]
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
      url: \${{ vars.STAGING_URL }}
    outputs:
      stack-name: \${{ steps.deploy.outputs.stack-name }}
    steps:
      - uses: actions/checkout@v4

${cdkSetupSteps}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: CDK Deploy Staging
        id: deploy
        run: |
          cd \$CDK_DIR
          cdk deploy --require-approval never \\
            --context environment=staging${needsDocker ? ` \\
            --context imageTag=\${{ needs.build.outputs.image-tag }}` : ''}
          echo "stack-name=${projectName}Stack-staging" >> $GITHUB_OUTPUT`
    );

    // ECS Reload Staging
    if (isEcs) {
      parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # RELOAD STAGING (force ECS to pull new task definition)
  # ════════════════════════════════════════════════════════════════════════════

  reload-staging:
    name: Reload Staging ECS
    runs-on: ubuntu-latest
    needs: deploy-staging
    permissions:
      id-token: write
      contents: read
    environment: staging
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Force new deployment
        run: |
          aws ecs update-service \\
            --cluster \${{ vars.ECS_CLUSTER_STAGING }} \\
            --service \${{ vars.ECS_SERVICE_STAGING }} \\
            --force-new-deployment

      - name: Wait for service stability
        run: |
          aws ecs wait services-stable \\
            --cluster \${{ vars.ECS_CLUSTER_STAGING }} \\
            --services \${{ vars.ECS_SERVICE_STAGING }}`
      );
    }

    // Load Testing
    const loadTestNeeds = isEcs ? 'reload-staging' : 'deploy-staging';
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # PERFORMANCE TESTING
  # ════════════════════════════════════════════════════════════════════════════

  load-test:
    name: Load Test (Staging)
    runs-on: ubuntu-latest
    needs: ${loadTestNeeds}
    environment: staging
    continue-on-error: true
    steps:
      - uses: actions/checkout@v4

      - name: Install k6
        run: |
          sudo gpg -k
          sudo gpg --no-default-keyring --keyring /usr/share/keyrings/k6-archive-keyring.gpg --keyserver hkp://keyserver.ubuntu.com:80 --recv-keys C5AD17C747E3415A3642D57D77C6C491D6AC1D69
          echo "deb [signed-by=/usr/share/keyrings/k6-archive-keyring.gpg] https://dl.k6.io/deb stable main" | sudo tee /etc/apt/sources.list.d/k6.list
          sudo apt-get update
          sudo apt-get install k6

      - name: Run load test
        run: |
          k6 run tests/load-test.js \\
            --vus 10 \\
            --duration 60s \\
            --env TARGET_URL=\${{ vars.STAGING_URL }}
        continue-on-error: true

      - name: Upload test results
        uses: actions/upload-artifact@v4
        if: always()
        with:
          name: k6-results
          path: k6-results.json
          retention-days: 7`
    );

    // Rollback Staging
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # ROLLBACK STAGING
  # ════════════════════════════════════════════════════════════════════════════

  rollback-staging:
    name: Rollback Staging
    runs-on: ubuntu-latest
    needs: deploy-staging
    if: failure() || cancelled()
    permissions:
      id-token: write
      contents: read
    environment: staging
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Rollback CloudFormation stack
        run: |
          aws cloudformation rollback-stack \\
            --stack-name \${{ needs.deploy-staging.outputs.stack-name }} || true
        continue-on-error: true`
    );

    // Production Release Gate
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # PRODUCTION RELEASE GATE
  # ════════════════════════════════════════════════════════════════════════════

  production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: load-test
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: |
          echo "✅ Production release approved for commit \${{ github.sha }}"
          echo "Approved by: \${{ github.actor }}"`
    );

    // Promote Docker Image (if applicable)
    if (needsDocker) {
      parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # PROMOTE IMAGE TO PRODUCTION TAG
  # ════════════════════════════════════════════════════════════════════════════

  promote-image:
    name: Promote Image to Production
    runs-on: ubuntu-latest
    needs: [production-approval, build]
    permissions:
      id-token: write
      contents: read
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Login to Amazon ECR
        id: login-ecr
        uses: aws-actions/amazon-ecr-login@v2

      - name: Tag image as production
        env:
          ECR_REGISTRY: \${{ steps.login-ecr.outputs.registry }}
        run: |
          MANIFEST=$(aws ecr batch-get-image \\
            --repository-name \${{ env.ECR_REPOSITORY }} \\
            --image-ids imageTag=\${{ needs.build.outputs.image-tag }} \\
            --query 'images[0].imageManifest' \\
            --output text)
          
          aws ecr put-image \\
            --repository-name \${{ env.ECR_REPOSITORY }} \\
            --image-tag production \\
            --image-manifest "$MANIFEST"`
      );
    }

    // Deploy Production
    const prodNeeds = needsDocker ? 'promote-image' : 'production-approval';
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # DEPLOY PRODUCTION
  # ════════════════════════════════════════════════════════════════════════════

  deploy-production:
    name: Deploy to Production
    runs-on: ubuntu-latest
    needs: ${prodNeeds}
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
      url: \${{ vars.PRODUCTION_URL }}
    outputs:
      stack-name: \${{ steps.deploy.outputs.stack-name }}
    steps:
      - uses: actions/checkout@v4

${cdkSetupSteps}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: CDK Deploy Production
        id: deploy
        run: |
          cd \$CDK_DIR
          cdk deploy --require-approval never \\
            --context environment=production${needsDocker ? ` \\
            --context imageTag=production` : ''}
          echo "stack-name=${projectName}Stack-production" >> $GITHUB_OUTPUT`
    );

    // ECS Reload Production
    if (isEcs) {
      parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # RELOAD PRODUCTION (force ECS to pull new task definition)
  # ════════════════════════════════════════════════════════════════════════════

  reload-production:
    name: Reload Production ECS
    runs-on: ubuntu-latest
    needs: deploy-production
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Force new deployment
        run: |
          aws ecs update-service \\
            --cluster \${{ vars.ECS_CLUSTER_PROD }} \\
            --service \${{ vars.ECS_SERVICE_PROD }} \\
            --force-new-deployment

      - name: Wait for service stability
        run: |
          aws ecs wait services-stable \\
            --cluster \${{ vars.ECS_CLUSTER_PROD }} \\
            --services \${{ vars.ECS_SERVICE_PROD }}`
      );
    }

    // Rollback Production
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # ROLLBACK PRODUCTION
  # ════════════════════════════════════════════════════════════════════════════

  rollback-production:
    name: Rollback Production
    runs-on: ubuntu-latest
    needs: deploy-production
    if: failure()
    permissions:
      id-token: write
      contents: read
    environment: production
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Rollback CloudFormation stack
        run: |
          aws cloudformation rollback-stack \\
            --stack-name \${{ needs.deploy-production.outputs.stack-name }} || true
        continue-on-error: true`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // TERRAFORM PIPELINE — Full staging/production flow
  // ══════════════════════════════════════════════════════════════════════════

  if (hasTf) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # VALIDATE — Terraform
  # ════════════════════════════════════════════════════════════════════════════

  terraform-validate:
    name: Terraform Validate
    runs-on: ubuntu-latest
    needs: test
    defaults:
      run:
        working-directory: \${{ env.TF_DIR }}
    steps:
      - uses: actions/checkout@v4

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9

      - name: Terraform Init
        run: terraform init -backend=false

      - name: Terraform Validate
        run: terraform validate

      - name: Terraform Format Check
        run: terraform fmt -check -recursive

  # ════════════════════════════════════════════════════════════════════════════
  # PLAN & APPLY STAGING
  # ════════════════════════════════════════════════════════════════════════════

  terraform-staging:
    name: Terraform Staging
    runs-on: ubuntu-latest
    needs: terraform-validate
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
    defaults:
      run:
        working-directory: \${{ env.TF_DIR }}
    steps:
      - uses: actions/checkout@v4

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Terraform Init
        run: terraform init

      - name: Terraform Plan (Staging)
        run: terraform plan -var="environment=staging" -out=tfplan-staging

      - name: Terraform Apply (Staging)
        run: terraform apply -auto-approve tfplan-staging

  # ════════════════════════════════════════════════════════════════════════════
  # PRODUCTION APPROVAL & APPLY
  # ════════════════════════════════════════════════════════════════════════════

  terraform-production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: terraform-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ Terraform production deployment approved"

  terraform-production:
    name: Terraform Production
    runs-on: ubuntu-latest
    needs: terraform-production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
    defaults:
      run:
        working-directory: \${{ env.TF_DIR }}
    steps:
      - uses: actions/checkout@v4

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Terraform Init
        run: terraform init

      - name: Terraform Plan (Production)
        run: terraform plan -var="environment=production" -out=tfplan-prod

      - name: Terraform Apply (Production)
        run: terraform apply -auto-approve tfplan-prod`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // SAM DEPLOY
  // ══════════════════════════════════════════════════════════════════════════

  if (hasSam) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # SAM — Staging & Production
  # ════════════════════════════════════════════════════════════════════════════

  sam-staging:
    name: SAM Deploy Staging
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Setup SAM CLI
        uses: aws-actions/setup-sam@v2

      - name: SAM Build
        run: sam build

      - name: SAM Deploy Staging
        run: |
          sam deploy \\
            --no-confirm-changeset \\
            --no-fail-on-empty-changeset \\
            --stack-name ${projectName}-staging \\
            --parameter-overrides Environment=staging \\
            --capabilities CAPABILITY_IAM

  sam-production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: sam-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ SAM production deployment approved"

  sam-production:
    name: SAM Deploy Production
    runs-on: ubuntu-latest
    needs: sam-production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '${pythonVer}'

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Setup SAM CLI
        uses: aws-actions/setup-sam@v2

      - name: SAM Build
        run: sam build

      - name: SAM Deploy Production
        run: |
          sam deploy \\
            --no-confirm-changeset \\
            --no-fail-on-empty-changeset \\
            --stack-name ${projectName}-production \\
            --parameter-overrides Environment=production \\
            --capabilities CAPABILITY_IAM`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // S3 + CloudFront — Full staging/production flow
  // ══════════════════════════════════════════════════════════════════════════

  if (isS3Cf && isNode && !hasCdk && !hasTf) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # DEPLOY STAGING (S3 + CloudFront)
  # ════════════════════════════════════════════════════════════════════════════

  deploy-staging:
    name: Deploy to Staging
    runs-on: ubuntu-latest
    needs: build
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
      url: \${{ vars.STAGING_URL }}
    steps:
      - name: Download artifact
        uses: actions/download-artifact@v4
        with:
          name: dist
          path: dist/

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy to S3 (Staging)
        run: aws s3 sync dist/ s3://\${{ vars.S3_BUCKET_STAGING }} --delete

      - name: Invalidate CloudFront (Staging)
        run: |
          aws cloudfront create-invalidation \\
            --distribution-id \${{ vars.CLOUDFRONT_DIST_STAGING }} \\
            --paths "/*"

  # ════════════════════════════════════════════════════════════════════════════
  # PRODUCTION APPROVAL & DEPLOY
  # ════════════════════════════════════════════════════════════════════════════

  production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: deploy-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ Production release approved"

  deploy-production:
    name: Deploy to Production
    runs-on: ubuntu-latest
    needs: production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
      url: \${{ vars.PRODUCTION_URL }}
    steps:
      - name: Download artifact
        uses: actions/download-artifact@v4
        with:
          name: dist
          path: dist/

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy to S3 (Production)
        run: aws s3 sync dist/ s3://\${{ vars.S3_BUCKET_PROD }} --delete

      - name: Invalidate CloudFront (Production)
        run: |
          aws cloudfront create-invalidation \\
            --distribution-id \${{ vars.CLOUDFRONT_DIST_PROD }} \\
            --paths "/*"`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // ECS Deploy (when no IaC selected)
  // ══════════════════════════════════════════════════════════════════════════

  if (isEcs && !hasCdk && !hasTf) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # DEPLOY STAGING (ECS — no IaC)
  # ════════════════════════════════════════════════════════════════════════════

  deploy-staging:
    name: Deploy to Staging (ECS)
    runs-on: ubuntu-latest
    needs: build
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy to ECS (Staging)
        run: |
          aws ecs update-service \\
            --cluster \${{ vars.ECS_CLUSTER_STAGING }} \\
            --service \${{ vars.ECS_SERVICE_STAGING }} \\
            --force-new-deployment

      - name: Wait for deployment
        run: |
          aws ecs wait services-stable \\
            --cluster \${{ vars.ECS_CLUSTER_STAGING }} \\
            --services \${{ vars.ECS_SERVICE_STAGING }}

  production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: deploy-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ Production release approved"

  deploy-production:
    name: Deploy to Production (ECS)
    runs-on: ubuntu-latest
    needs: production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
    steps:
      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy to ECS (Production)
        run: |
          aws ecs update-service \\
            --cluster \${{ vars.ECS_CLUSTER_PROD }} \\
            --service \${{ vars.ECS_SERVICE_PROD }} \\
            --force-new-deployment

      - name: Wait for deployment
        run: |
          aws ecs wait services-stable \\
            --cluster \${{ vars.ECS_CLUSTER_PROD }} \\
            --services \${{ vars.ECS_SERVICE_PROD }}`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // Lambda Deploy (when no IaC selected)
  // ══════════════════════════════════════════════════════════════════════════

  if (isLambdaInfra && !hasCdk && !hasSam && !hasTf) {
    const pkgCmd = isPython
      ? `          pip install -r requirements.txt -t ./package/
          cp -r *.py ./package/
          cd package && zip -r ../function.zip . && cd ..`
      : isNode
      ? `          npm ci
          zip -r function.zip . -x "*.git*"`
      : `          mvn package -DskipTests -q
          cp target/*.jar function.zip`;

    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # DEPLOY LAMBDA
  # ════════════════════════════════════════════════════════════════════════════

  package-lambda:
    name: Package Lambda
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    steps:
      - uses: actions/checkout@v4

      - name: Package Lambda
        run: |
${pkgCmd}

      - name: Upload artifact
        uses: actions/upload-artifact@v4
        with:
          name: lambda-package
          path: function.zip

  deploy-staging:
    name: Deploy to Staging (Lambda)
    runs-on: ubuntu-latest
    needs: package-lambda
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
    steps:
      - name: Download artifact
        uses: actions/download-artifact@v4
        with:
          name: lambda-package

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy Lambda (Staging)
        run: |
          aws lambda update-function-code \\
            --function-name \${{ vars.LAMBDA_FUNCTION_STAGING }} \\
            --zip-file fileb://function.zip
          aws lambda wait function-updated \\
            --function-name \${{ vars.LAMBDA_FUNCTION_STAGING }}

  production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: deploy-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ Production release approved"

  deploy-production:
    name: Deploy to Production (Lambda)
    runs-on: ubuntu-latest
    needs: production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
    steps:
      - name: Download artifact
        uses: actions/download-artifact@v4
        with:
          name: lambda-package

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy Lambda (Production)
        run: |
          aws lambda update-function-code \\
            --function-name \${{ vars.LAMBDA_FUNCTION_PROD }} \\
            --zip-file fileb://function.zip
          aws lambda wait function-updated \\
            --function-name \${{ vars.LAMBDA_FUNCTION_PROD }}`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // CloudFormation Deploy (when hasCfn)
  // ══════════════════════════════════════════════════════════════════════════

  if (hasCfn) {
    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # CLOUDFORMATION — Staging & Production
  # ════════════════════════════════════════════════════════════════════════════

  cfn-staging:
    name: CloudFormation Deploy Staging
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy CloudFormation Stack (Staging)
        run: |
          aws cloudformation deploy \\
            --template-file devops/cloudformation/template.yaml \\
            --stack-name ${projectName}-staging \\
            --parameter-overrides Environment=staging \\
            --capabilities CAPABILITY_IAM CAPABILITY_NAMED_IAM \\
            --no-fail-on-empty-changeset

  cfn-production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: cfn-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ CloudFormation production deployment approved"

  cfn-production:
    name: CloudFormation Deploy Production
    runs-on: ubuntu-latest
    needs: cfn-production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Deploy CloudFormation Stack (Production)
        run: |
          aws cloudformation deploy \\
            --template-file devops/cloudformation/template.yaml \\
            --stack-name ${projectName}-production \\
            --parameter-overrides Environment=production \\
            --capabilities CAPABILITY_IAM CAPABILITY_NAMED_IAM \\
            --no-fail-on-empty-changeset`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // Pulumi Deploy (when hasPulumiPy or hasPulumiTs)
  // ══════════════════════════════════════════════════════════════════════════

  if (hasPulumiPy || hasPulumiTs) {
    const pulumiSetup = hasPulumiTs
      ? `      - uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'
          cache-dependency-path: devops/pulumi/package-lock.json

      - name: Install Pulumi dependencies
        run: cd devops/pulumi && npm ci`
      : `      - uses: actions/setup-python@v5
        with:
          python-version: '${cfg.pythonVersion ?? '3.14'}'

      - name: Install Pulumi dependencies
        run: |
          pip install pulumi pulumi-aws
          cd devops/pulumi && pip install -r requirements.txt`;

    parts.push(
`
  # ════════════════════════════════════════════════════════════════════════════
  # PULUMI — Preview on PR, Up on main
  # ════════════════════════════════════════════════════════════════════════════

  pulumi-preview:
    name: Pulumi Preview
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'pull_request'
    permissions:
      id-token: write
      contents: read
    steps:
      - uses: actions/checkout@v4

${pulumiSetup}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Pulumi Preview
        uses: pulumi/actions@v5
        with:
          command: preview
          stack-name: staging
          work-dir: devops/pulumi
        env:
          PULUMI_ACCESS_TOKEN: \${{ secrets.PULUMI_ACCESS_TOKEN }}

  pulumi-staging:
    name: Pulumi Up (Staging)
    runs-on: ubuntu-latest
    needs: test
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    environment:
      name: staging
    steps:
      - uses: actions/checkout@v4

${pulumiSetup}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Pulumi Up (Staging)
        uses: pulumi/actions@v5
        with:
          command: up
          stack-name: staging
          work-dir: devops/pulumi
        env:
          PULUMI_ACCESS_TOKEN: \${{ secrets.PULUMI_ACCESS_TOKEN }}

  pulumi-production-approval:
    name: Production Approval
    runs-on: ubuntu-latest
    needs: pulumi-staging
    environment:
      name: production-approval
    steps:
      - name: Approval checkpoint
        run: echo "✅ Pulumi production deployment approved"

  pulumi-production:
    name: Pulumi Up (Production)
    runs-on: ubuntu-latest
    needs: pulumi-production-approval
    permissions:
      id-token: write
      contents: read
    environment:
      name: production
    steps:
      - uses: actions/checkout@v4

${pulumiSetup}

      - name: Configure AWS credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: \${{ env.AWS_REGION }}

      - name: Pulumi Up (Production)
        uses: pulumi/actions@v5
        with:
          command: up
          stack-name: production
          work-dir: devops/pulumi
        env:
          PULUMI_ACCESS_TOKEN: \${{ secrets.PULUMI_ACCESS_TOKEN }}`
    );
  }

  // ── Feature: security / quality / docker-lint jobs ───────────────────────
  const secJobs = githubSecurityJobs(feat);
  if (secJobs) parts.push(secJobs);

  // ── Feature: Slack notification job (last, needs deploy-production) ──────
  const slackJob = githubSlackJob(feat, projectName);
  if (slackJob) parts.push(slackJob);

  return parts.join('\n');
}

