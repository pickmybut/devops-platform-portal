/**
 * Basic Pipeline — dynamic Bitbucket Pipelines generator.
 *
 * Composes test + deploy steps based on:
 *   projectType     — what language / framework is being used
 *   iac             — what infrastructure tool will be deployed
 *   projectTypeConfig — version + database choices
 */

function generate({ projectName, appName, projectType, iac, infra, projectTypeConfig }) {
  const ptId   = projectType?.id ?? null;
  const iacId  = iac?.id         ?? 'none';
  const infraId= infra?.id       ?? 'none';
  const cfg    = projectTypeConfig ?? {};

  // ── Project-type flags ──────────────────────────────────────────────────
  const isDjango      = ptId === 'django-api';
  const isFastApi     = ptId === 'fastapi';
  const isLambdaPy    = ptId === 'python-lambda';
  const isServerless  = ptId === 'serverless';
  const isPythonApp   = isDjango || isFastApi;
  const isPython      = isPythonApp || isLambdaPy || isServerless;
  const isJava        = ptId === 'java-spring' || ptId === 'java-lambda';
  const isMfe         = ptId === 'react-mfe' || ptId === 'react-shell';
  const isNodeApi     = ptId === 'nodejs-api';
  const isNodeLambda  = ptId === 'nodejs-lambda';
  const isNode        = isMfe || isNodeApi || isNodeLambda;
  const isDotnet      = ptId === 'dotnet-api';

  // ── IaC flags ───────────────────────────────────────────────────────────
  const hasPyCdk    = iacId === 'python-cdk';
  const hasTsCdk    = iacId === 'typescript-cdk';
  const hasCdk      = hasPyCdk || hasTsCdk || iacId === 'csharp-cdk';
  const hasTf       = iacId === 'terraform';
  const hasSam      = iacId === 'sam';

  // ── Infra architecture flags ─────────────────────────────────────────────
  const isEcs         = infraId === 'ecs-fargate' || infraId === 'ecs-ec2';
  const isLambdaInfra = infraId === 'lambda';
  const isS3Cf        = infraId === 's3-cloudfront';
  const needsDocker   = isEcs;

  // ── Config values ───────────────────────────────────────────────────────
  const pythonVer  = cfg.pythonVersion  ?? '3.14';
  const javaVer    = cfg.javaVersion    ?? '21';
  const nodeVer    = cfg.nodeVersion    ?? '26';
  const dotnetVer  = cfg.dotnetVersion  ?? '8.0';
  const database   = cfg.database       ?? 'postgresql';

  const needsPostgres = isPythonApp && database === 'postgresql';

  const parts = [];

  // ── Header ──────────────────────────────────────────────────────────────
  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# Bitbucket Pipelines — ${projectName}
# Generated by the DevOps Self-Service Portal
#
# Project type : ${projectType?.name  ?? 'None'}
# IaC          : ${iac && iacId !== 'none' ? iac.name : 'None'}
#
# Required repository variables (Repository settings → Pipelines → Variables):
#   AWS_ACCESS_KEY_ID
#   AWS_SECRET_ACCESS_KEY
#   AWS_DEFAULT_REGION
# ──────────────────────────────────────────────────────────────────────────────

image: atlassian/default-image:4

definitions:
  caches:
    pip: ~/.cache/pip
    npm: ~/.npm

  services:${needsPostgres ? `
    postgres:
      image: postgres:16-alpine
      variables:
        POSTGRES_DB: ${appName}_test
        POSTGRES_USER: postgres
        POSTGRES_PASSWORD: postgres` : `
    docker:
      memory: 2048`}

pipelines:`
  );

  // ══════════════════════════════════════════════════════════════════════════
  // DEFAULT (runs on all branches)
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`  default:`);

  // ── Python Test Step ────────────────────────────────────────────────────
  if (isPython) {
    parts.push(
`    - step:
        name: Test
        image: python:${pythonVer}-slim
        caches:
          - pip${needsPostgres ? `
        services:
          - postgres` : ''}
        script:
          - pip install -r requirements.txt
          - pip install ruff pytest pytest-cov
          - ruff check .
          - pytest --cov=. --cov-report=xml -v${needsPostgres ? `
        variables:
          DATABASE_URL: postgres://postgres:postgres@localhost:5432/${appName}_test` : ''}`
    );
  }

  // ── Java Test Step ──────────────────────────────────────────────────────
  if (isJava) {
    parts.push(
`    - step:
        name: Test
        image: maven:3.9-eclipse-temurin-${javaVer}
        caches:
          - maven
        script:
          - mvn test -q`
    );
  }

  // ── Node Test Step ──────────────────────────────────────────────────────
  if (isNode) {
    parts.push(
`    - step:
        name: Test
        image: node:${nodeVer}-slim
        caches:
          - npm
        script:
          - npm ci
          - npm run lint
          - npm test`
    );
  }

  // ── .NET Test Step ──────────────────────────────────────────────────────
  if (isDotnet) {
    parts.push(
`    - step:
        name: Test
        image: mcr.microsoft.com/dotnet/sdk:${dotnetVer}
        script:
          - dotnet restore
          - dotnet test --no-restore --verbosity minimal`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // BRANCHES (main/master deployments)
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`
  branches:
    main:`);

  // ── Repeat test step for main branch ────────────────────────────────────
  if (isPython) {
    parts.push(
`      - step:
          name: Test
          image: python:${pythonVer}-slim
          caches:
            - pip${needsPostgres ? `
          services:
            - postgres` : ''}
          script:
            - pip install -r requirements.txt
            - pip install ruff pytest pytest-cov
            - ruff check .
            - pytest --cov=. --cov-report=xml -v${needsPostgres ? `
          variables:
            DATABASE_URL: postgres://postgres:postgres@localhost:5432/${appName}_test` : ''}`
    );
  } else if (isJava) {
    parts.push(
`      - step:
          name: Test
          image: maven:3.9-eclipse-temurin-${javaVer}
          caches:
            - maven
          script:
            - mvn test -q`
    );
  } else if (isNode) {
    parts.push(
`      - step:
          name: Test
          image: node:${nodeVer}-slim
          caches:
            - npm
          script:
            - npm ci
            - npm run lint
            - npm test`
    );
  } else if (isDotnet) {
    parts.push(
`      - step:
          name: Test
          image: mcr.microsoft.com/dotnet/sdk:${dotnetVer}
          script:
            - dotnet restore
            - dotnet test --no-restore --verbosity minimal`
    );
  }

  // ── Docker Build Step ───────────────────────────────────────────────────
  if (needsDocker) {
    parts.push(
`      - step:
          name: Build & Push Docker Image
          services:
            - docker
          script:
            - export IMAGE_TAG=$BITBUCKET_COMMIT
            - export ECR_REGISTRY=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com
            - pipe: atlassian/aws-ecr-push-image:2.4.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                IMAGE_NAME: ${appName}
                TAGS: $IMAGE_TAG`
    );
  }

  // ── S3 + CloudFront Deploy ──────────────────────────────────────────────
  if (isS3Cf && isNode) {
    parts.push(
`      - step:
          name: Build
          image: node:${nodeVer}-slim
          caches:
            - npm
          script:
            - npm ci
            - npm run build
          artifacts:
            - dist/**

      - step:
          name: Deploy to S3
          deployment: production
          script:
            - pipe: atlassian/aws-s3-deploy:1.6.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                S3_BUCKET: $S3_BUCKET_NAME
                LOCAL_PATH: dist/
                DELETE_FLAG: 'true'
            - pipe: atlassian/aws-cloudfront-invalidate:1.0.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                DISTRIBUTION_ID: $CLOUDFRONT_DISTRIBUTION_ID`
    );
  }

  // ── CDK Deploy ──────────────────────────────────────────────────────────
  if (hasCdk) {
    const cdkImage = hasTsCdk ? `node:20-slim` : `python:${pythonVer}-slim`;
    const cdkInstall = hasTsCdk
      ? `            - npm ci
            - npm install -g aws-cdk`
      : `            - pip install -r requirements.txt
            - npm install -g aws-cdk`;

    parts.push(
`      - step:
          name: CDK Deploy
          image: ${cdkImage}
          deployment: production
          script:
            - cd devops/cdk
${cdkInstall}
            - cdk deploy --require-approval never${needsDocker ? ' --context imageTag=$BITBUCKET_COMMIT' : ''}`
    );
  }

  // ── Terraform Deploy ────────────────────────────────────────────────────
  if (hasTf) {
    parts.push(
`      - step:
          name: Terraform Plan
          image: hashicorp/terraform:1.9
          script:
            - cd devops/terraform
            - terraform init
            - terraform plan -out=tfplan
          artifacts:
            - devops/terraform/tfplan

      - step:
          name: Terraform Apply
          image: hashicorp/terraform:1.9
          deployment: production
          trigger: manual
          script:
            - cd devops/terraform
            - terraform init
            - terraform apply -auto-approve tfplan`
    );
  }

  // ── SAM Deploy ──────────────────────────────────────────────────────────
  if (hasSam) {
    parts.push(
`      - step:
          name: SAM Deploy
          image: public.ecr.aws/sam/build-python${pythonVer}:latest
          deployment: production
          script:
            - sam build
            - sam deploy --no-confirm-changeset --no-fail-on-empty-changeset --stack-name ${projectName} --capabilities CAPABILITY_IAM`
    );
  }

  // ── ECS Deploy (when no CDK) ────────────────────────────────────────────
  if (isEcs && !hasCdk && !hasTf) {
    parts.push(
`      - step:
          name: Deploy to ECS
          deployment: production
          script:
            - pipe: atlassian/aws-ecs-deploy:2.2.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                CLUSTER_NAME: $ECS_CLUSTER_NAME
                SERVICE_NAME: $ECS_SERVICE_NAME
                FORCE_NEW_DEPLOYMENT: 'true'`
    );
  }

  // ── Lambda Deploy (when no CDK/SAM) ─────────────────────────────────────
  if (isLambdaInfra && !hasCdk && !hasSam && !hasTf) {
    const pkgScript = isPython
      ? `            - pip install -r requirements.txt -t ./package/
            - cp -r *.py ./package/
            - cd package && zip -r ../function.zip . && cd ..`
      : isNode
      ? `            - npm ci
            - zip -r function.zip . -x "*.git*"`
      : `            - mvn package -DskipTests -q
            - cp target/*.jar function.zip`;

    parts.push(
`      - step:
          name: Package Lambda
          script:
${pkgScript}
          artifacts:
            - function.zip

      - step:
          name: Deploy to Lambda
          deployment: production
          script:
            - pipe: atlassian/aws-lambda-deploy:1.10.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                FUNCTION_NAME: $LAMBDA_FUNCTION_NAME
                ZIP_FILE: function.zip`
    );
  }

  return parts.join('\n');
}

// ─────────────────────────────────────────────────────────────────────────────
// Public API
// ─────────────────────────────────────────────────────────────────────────────

export function buildBasicPipelineFiles(vars) {
  const content = generate(vars);
  return [{ path: 'bitbucket-pipelines.yml', content }];
}

