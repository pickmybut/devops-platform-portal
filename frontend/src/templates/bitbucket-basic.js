/**
 * Basic Pipeline — dynamic Bitbucket Pipelines generator.
 *
 * Full pipeline with staging/production environments, manual triggers, and rollbacks.
 *
 * Composes test + deploy steps based on:
 *   projectType     — what language / framework is being used
 *   iac             — what infrastructure tool will be deployed
 *   projectTypeConfig — version + database choices
 *   features        — additional features to inject
 */

import {
  parseFeatureFlags,
  bitbucketSecurityStepDefs,
  bitbucketDefaultFeatureSteps,
  bitbucketMainFeatureSteps,
  bitbucketSlackMainStep,
  bitbucketAiReviewStepDef,
  bitbucketAiReviewPipelineStep,
  bitbucketSecretDetectionStepDef,
  bitbucketContainerScanStepDef,
  bitbucketDastStepDef,
  bitbucketSonarCloudStepDef,
  bitbucketInfracostStepDef,
  bitbucketMsTeamsStepDef,
  bitbucketMsTeamsMainStep,
  bitbucketSmokeTestStepDef,
  bitbucketSmokeTestStagingStep,
  bitbucketSmokeTestProductionStep,
  bitbucketReleaseAutoStepDef,
  bitbucketReleaseAutoMainStep,
  featureRequirementsComment,
} from './feature-snippets.js';

function generate({ projectName, appName, projectType, iac, infra, projectTypeConfig, features = [] }) {
  const ptId   = projectType?.id ?? null;
  const iacId  = iac?.id         ?? 'none';
  const infraId= infra?.id       ?? 'none';
  const cfg    = projectTypeConfig ?? {};

  // ── Project-type flags ──────────────────────────────────────────────────
  const isDjango      = ptId === 'django-api';
  const isFastApi     = ptId === 'fastapi';
  const isLambdaPy    = ptId === 'python-lambda';
  const isServerless  = ptId === 'serverless';
  const isApiGateway  = ptId === 'api-gateway';
  const isCdkStack    = ptId === 'cdk-stack';
  const isPythonApp   = isDjango || isFastApi;
  const isPython      = isPythonApp || isLambdaPy || isServerless || isApiGateway;
  const isJava        = ptId === 'java-spring' || ptId === 'java-lambda';
  const isMfe         = ptId === 'react-mfe' || ptId === 'react-shell';
  const isNodeApi     = ptId === 'nodejs-api';
  const isNodeLambda  = ptId === 'nodejs-lambda';
  const isNode        = isMfe || isNodeApi || isNodeLambda || isCdkStack;
  const isDotnet      = ptId === 'dotnet-api';

  // ── IaC flags ───────────────────────────────────────────────────────────
  const hasPyCdk    = iacId === 'python-cdk';
  const hasTsCdk    = iacId === 'typescript-cdk';
  const hasCsharpCdk= iacId === 'csharp-cdk';
  const hasCdk      = hasPyCdk || hasTsCdk || hasCsharpCdk || isCdkStack;
  const hasTf       = iacId === 'terraform';
  const hasCfn      = iacId === 'cloudformation';
  const hasSam      = iacId === 'sam';
  const hasPulumiPy = iacId === 'pulumi-python';
  const hasPulumiTs = iacId === 'pulumi-ts';
  const hasIac      = iacId !== 'none';

  // ── Infra architecture flags ─────────────────────────────────────────────
  const isEcsFargate  = infraId === 'ecs-fargate';
  const isEcsEc2      = infraId === 'ecs-ec2';
  const isEcs         = isEcsFargate || isEcsEc2;
  const isEks         = infraId === 'eks';
  const isK8sEc2      = infraId === 'k8s-ec2';
  const isLambdaInfra = infraId === 'lambda';
  const isS3Cf        = infraId === 's3-cloudfront';
  const isEc2         = infraId === 'ec2';
  const needsDocker   = isEcs || isEks || isK8sEc2;
  const hasInfraArch  = infraId !== 'none';

  // ── Feature flags ─────────────────────────────────────────────────────────
  const feat = parseFeatureFlags(features, { needsDocker, hasTf, hasCdk });

  // ── Config values ───────────────────────────────────────────────────────
  const pythonVer  = cfg.pythonVersion  ?? '3.14';
  const javaVer    = cfg.javaVersion    ?? '21';
  const nodeVer    = cfg.nodeVersion    ?? '26';
  const dotnetVer  = cfg.dotnetVersion  ?? '8.0';
  const database   = cfg.database       ?? 'postgresql';

  const needsPostgres = isPythonApp && database === 'postgresql';
  const needsMysql    = isPythonApp && database === 'mysql';

  const parts = [];

  // ── Header ──────────────────────────────────────────────────────────────
  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# Bitbucket Pipelines — ${projectName}
# Generated by the DevOps Self-Service Portal
#
# Project type : ${projectType?.name  ?? 'None'}
# IaC          : ${iac && iacId !== 'none' ? iac.name : 'None'}
# Infra        : ${infra && infraId !== 'none' ? infra.name : 'None'}
#
# Required repository variables (Repository settings → Pipelines → Variables):
#   AWS_ACCESS_KEY_ID        — IAM access key (secured)
#   AWS_SECRET_ACCESS_KEY    — IAM secret key (secured)
#   AWS_DEFAULT_REGION       — e.g. eu-west-2
#   AWS_ACCOUNT_ID           — AWS account ID${isEcs ? `
#   ECS_CLUSTER_STAGING      — ECS cluster name for staging
#   ECS_SERVICE_STAGING      — ECS service name for staging
#   ECS_CLUSTER_PROD         — ECS cluster name for production
#   ECS_SERVICE_PROD         — ECS service name for production` : ''}${isEks ? `
#   EKS_CLUSTER_NAME         — EKS cluster name
#   K8S_NAMESPACE            — Kubernetes namespace (default: default)` : ''}${isK8sEc2 ? `
#   K8S_NAMESPACE            — Kubernetes namespace
#   KUBE_CONFIG              — Base64-encoded kubeconfig` : ''}${isEc2 ? `
#   CODEDEPLOY_APP           — CodeDeploy application name
#   CODEDEPLOY_GROUP_STAGING — CodeDeploy deployment group for staging
#   CODEDEPLOY_GROUP_PROD    — CodeDeploy deployment group for production
#   S3_ARTIFACT_BUCKET       — S3 bucket for deployment artifacts` : ''}${isS3Cf ? `
#   S3_BUCKET_STAGING        — S3 bucket for staging
#   S3_BUCKET_PROD           — S3 bucket for production
#   CLOUDFRONT_DIST_STAGING  — CloudFront distribution ID for staging
#   CLOUDFRONT_DIST_PROD     — CloudFront distribution ID for production` : ''}
#
# Deployment environments must be configured in:
#   Repository settings → Deployments → Add environment
#   - staging
#   - production (with required reviewers)
# ──────────────────────────────────────────────────────────────────────────────

image: atlassian/default-image:4

options:
  max-time: 30

definitions:
  caches:
    pip: ~/.cache/pip
    npm: ~/.npm

  services:${needsPostgres ? `
    postgres:
      image: postgres:16-alpine
      variables:
        POSTGRES_DB: ${appName}_test
        POSTGRES_USER: postgres
        POSTGRES_PASSWORD: postgres` : ''}${needsMysql ? `
    mysql:
      image: mysql:8.0
      variables:
        MYSQL_DATABASE: ${appName}_test
        MYSQL_ROOT_PASSWORD: root` : ''}
    docker:
      memory: 3072

  steps:`
  );

  // ══════════════════════════════════════════════════════════════════════════
  // REUSABLE STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  // ── Python Test Step Definition ─────────────────────────────────────────
  if (isPython) {
    parts.push(
`    - step: &test-python
        name: Test
        image: python:${pythonVer}-slim
        caches:
          - pip${needsPostgres ? `
        services:
          - postgres` : ''}${needsMysql ? `
        services:
          - mysql` : ''}
        script:
          - pip install -r requirements.txt
          - pip install ruff pytest pytest-cov
          - ruff check .
          - pytest --cov=. --cov-report=xml --cov-report=term -v${needsPostgres ? `
        variables:
          DATABASE_URL: postgres://postgres:postgres@localhost:5432/${appName}_test` : ''}${needsMysql ? `
        variables:
          DATABASE_URL: mysql+pymysql://root:root@localhost:3306/${appName}_test` : ''}`
    );
  }

  // ── Java Test Step Definition ───────────────────────────────────────────
  if (isJava) {
    parts.push(
`    - step: &test-java
        name: Test
        image: maven:3.9-eclipse-temurin-${javaVer}
        caches:
          - maven
        script:
          - mvn test -q
        artifacts:
          - target/surefire-reports/**`
    );
  }

  // ── Node Test Step Definition ───────────────────────────────────────────
  if (isNode) {
    parts.push(
`    - step: &test-node
        name: Test
        image: node:${nodeVer}-slim
        caches:
          - npm
        script:
          - npm ci
          - npm run lint
          - npm test -- --coverage`
    );
  }

  // ── .NET Test Step Definition ───────────────────────────────────────────
  if (isDotnet) {
    parts.push(
`    - step: &test-dotnet
        name: Test
        image: mcr.microsoft.com/dotnet/sdk:${dotnetVer}
        script:
          - dotnet restore
          - dotnet test --no-restore --verbosity minimal`
    );
  }

  // ── Docker Build Step Definition ────────────────────────────────────────
  if (needsDocker) {
    parts.push(
`
    - step: &build-docker
        name: Build & Push Docker Image
        services:
          - docker
        caches:
          - docker
        script:
          - export IMAGE_TAG=$BITBUCKET_COMMIT
          - export ECR_REGISTRY=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com
          - export ECR_REPO=${appName}
          - pipe: atlassian/aws-ecr-push-image:2.4.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              IMAGE_NAME: $ECR_REPO
              TAGS: $IMAGE_TAG
          - echo "IMAGE_TAG=$IMAGE_TAG" >> image.env
        artifacts:
          - image.env`
    );
  }

  // ── Node Build Step Definition ──────────────────────────────────────────
  if (isNode && (isS3Cf || isMfe)) {
    parts.push(
`
    - step: &build-node
        name: Build
        image: node:${nodeVer}-slim
        caches:
          - npm
        script:
          - npm ci
          - npm run build
        artifacts:
          - dist/**`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // CDK STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  if (hasCdk) {
    const cdkImage = hasTsCdk ? `node:20-slim` : `python:${pythonVer}-slim`;
    const cdkInstall = hasTsCdk
      ? `          - npm ci
          - npm install -g aws-cdk`
      : `          - pip install -r requirements.txt
          - npm install -g aws-cdk`;

    parts.push(
`
    - step: &cdk-synth
        name: CDK Synth
        image: ${cdkImage}
        script:
          - cd devops/cdk
${cdkInstall}
          - cdk synth

    - step: &cdk-deploy-staging
        name: CDK Deploy Staging
        image: ${cdkImage}
        deployment: staging
        script:
          - cd devops/cdk
${cdkInstall}
          - cdk deploy --require-approval never --context environment=staging${needsDocker ? ' --context imageTag=$BITBUCKET_COMMIT' : ''}

    - step: &cdk-deploy-production
        name: CDK Deploy Production
        image: ${cdkImage}
        deployment: production
        trigger: manual
        script:
          - cd devops/cdk
${cdkInstall}
          - cdk deploy --require-approval never --context environment=production${needsDocker ? ' --context imageTag=$BITBUCKET_COMMIT' : ''}`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // TERRAFORM STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  if (hasTf) {
    parts.push(
`
    - step: &terraform-validate
        name: Terraform Validate
        image: hashicorp/terraform:1.9
        script:
          - cd devops/terraform
          - terraform init -backend=false
          - terraform validate
          - terraform fmt -check -recursive

    - step: &terraform-plan-staging
        name: Terraform Plan (Staging)
        image: hashicorp/terraform:1.9
        script:
          - cd devops/terraform
          - terraform init
          - terraform plan -var="environment=staging" -out=tfplan-staging
        artifacts:
          - devops/terraform/tfplan-staging

    - step: &terraform-apply-staging
        name: Terraform Apply (Staging)
        image: hashicorp/terraform:1.9
        deployment: staging
        script:
          - cd devops/terraform
          - terraform init
          - terraform apply -auto-approve tfplan-staging

    - step: &terraform-plan-production
        name: Terraform Plan (Production)
        image: hashicorp/terraform:1.9
        script:
          - cd devops/terraform
          - terraform init
          - terraform plan -var="environment=production" -out=tfplan-prod
        artifacts:
          - devops/terraform/tfplan-prod

    - step: &terraform-apply-production
        name: Terraform Apply (Production)
        image: hashicorp/terraform:1.9
        deployment: production
        trigger: manual
        script:
          - cd devops/terraform
          - terraform init
          - terraform apply -auto-approve tfplan-prod

    - step: &terraform-destroy
        name: Terraform Destroy
        image: hashicorp/terraform:1.9
        trigger: manual
        script:
          - cd devops/terraform
          - terraform init
          - terraform destroy -auto-approve`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // SAM STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  if (hasSam) {
    parts.push(
`
    - step: &sam-build
        name: SAM Build
        image: public.ecr.aws/sam/build-python${pythonVer}:latest
        script:
          - sam build
        artifacts:
          - .aws-sam/**

    - step: &sam-deploy-staging
        name: SAM Deploy Staging
        image: public.ecr.aws/sam/build-python${pythonVer}:latest
        deployment: staging
        script:
          - sam deploy --no-confirm-changeset --no-fail-on-empty-changeset --stack-name ${projectName}-staging --parameter-overrides Environment=staging --capabilities CAPABILITY_IAM

    - step: &sam-deploy-production
        name: SAM Deploy Production
        image: public.ecr.aws/sam/build-python${pythonVer}:latest
        deployment: production
        trigger: manual
        script:
          - sam deploy --no-confirm-changeset --no-fail-on-empty-changeset --stack-name ${projectName}-production --parameter-overrides Environment=production --capabilities CAPABILITY_IAM`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // ECS DEPLOY STEP DEFINITIONS (when no IaC)
  // ══════════════════════════════════════════════════════════════════════════

  if (isEcs && !hasCdk && !hasTf) {
    parts.push(
`
    - step: &ecs-deploy-staging
        name: Deploy to ECS (Staging)
        deployment: staging
        script:
          - pipe: atlassian/aws-ecs-deploy:2.2.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              CLUSTER_NAME: $ECS_CLUSTER_STAGING
              SERVICE_NAME: $ECS_SERVICE_STAGING
              FORCE_NEW_DEPLOYMENT: 'true'

    - step: &ecs-deploy-production
        name: Deploy to ECS (Production)
        deployment: production
        trigger: manual
        script:
          - pipe: atlassian/aws-ecs-deploy:2.2.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              CLUSTER_NAME: $ECS_CLUSTER_PROD
              SERVICE_NAME: $ECS_SERVICE_PROD
              FORCE_NEW_DEPLOYMENT: 'true'`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // EKS DEPLOY STEP DEFINITIONS (when no IaC)
  // ══════════════════════════════════════════════════════════════════════════

  if (isEks && !hasCdk && !hasTf) {
    parts.push(
`
    - step: &eks-deploy-staging
        name: Deploy to EKS (Staging)
        image: amazon/aws-cli:latest
        deployment: staging
        script:
          - aws eks update-kubeconfig --name $EKS_CLUSTER_NAME --region $AWS_DEFAULT_REGION
          - export IMAGE_TAG=$BITBUCKET_COMMIT
          - export ECR_REGISTRY=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com
          - helm upgrade --install ${appName}-staging ./helm/${appName}
              --namespace \${K8S_NAMESPACE:-default}
              --set image.repository=$ECR_REGISTRY/${appName}
              --set image.tag=$IMAGE_TAG
              --set environment=staging
              --wait --timeout 5m

    - step: &eks-deploy-production
        name: Deploy to EKS (Production)
        image: amazon/aws-cli:latest
        deployment: production
        trigger: manual
        script:
          - aws eks update-kubeconfig --name $EKS_CLUSTER_NAME --region $AWS_DEFAULT_REGION
          - export IMAGE_TAG=$BITBUCKET_COMMIT
          - export ECR_REGISTRY=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com
          - helm upgrade --install ${appName}-production ./helm/${appName}
              --namespace \${K8S_NAMESPACE:-production}
              --set image.repository=$ECR_REGISTRY/${appName}
              --set image.tag=$IMAGE_TAG
              --set environment=production
              --wait --timeout 5m`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // K8S-EC2 DEPLOY STEP DEFINITIONS (when no IaC)
  // ══════════════════════════════════════════════════════════════════════════

  if (isK8sEc2 && !hasCdk && !hasTf) {
    parts.push(
`
    - step: &k8s-deploy-staging
        name: Deploy to K8s/EC2 (Staging)
        image: bitnami/kubectl:latest
        deployment: staging
        script:
          - echo $KUBE_CONFIG | base64 -d > /tmp/kubeconfig
          - export KUBECONFIG=/tmp/kubeconfig
          - export IMAGE_TAG=$BITBUCKET_COMMIT
          - export ECR_REGISTRY=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com
          - sed -i "s|IMAGE_PLACEHOLDER|$ECR_REGISTRY/${appName}:$IMAGE_TAG|g" k8s/staging/*.yaml
          - kubectl apply -f k8s/staging/ --namespace \${K8S_NAMESPACE:-default}
          - kubectl rollout status deployment/${appName} --namespace \${K8S_NAMESPACE:-default} --timeout=5m

    - step: &k8s-deploy-production
        name: Deploy to K8s/EC2 (Production)
        image: bitnami/kubectl:latest
        deployment: production
        trigger: manual
        script:
          - echo $KUBE_CONFIG | base64 -d > /tmp/kubeconfig
          - export KUBECONFIG=/tmp/kubeconfig
          - export IMAGE_TAG=$BITBUCKET_COMMIT
          - export ECR_REGISTRY=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com
          - sed -i "s|IMAGE_PLACEHOLDER|$ECR_REGISTRY/${appName}:$IMAGE_TAG|g" k8s/production/*.yaml
          - kubectl apply -f k8s/production/ --namespace \${K8S_NAMESPACE:-production}
          - kubectl rollout status deployment/${appName} --namespace \${K8S_NAMESPACE:-production} --timeout=5m`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // EC2 CODEDEPLOY STEP DEFINITIONS (when no IaC)
  // ══════════════════════════════════════════════════════════════════════════

  if (isEc2 && !hasCdk && !hasTf) {
    parts.push(
`
    - step: &ec2-deploy-staging
        name: Deploy to EC2 (Staging)
        deployment: staging
        script:
          - zip -r deploy.zip . -x "*.git*" "node_modules/.cache/*" "__pycache__/*"
          - aws s3 cp deploy.zip s3://$S3_ARTIFACT_BUCKET/${projectName}/staging/$BITBUCKET_COMMIT.zip
          - aws deploy create-deployment
              --application-name $CODEDEPLOY_APP
              --deployment-group-name $CODEDEPLOY_GROUP_STAGING
              --s3-location bucket=$S3_ARTIFACT_BUCKET,key=${projectName}/staging/$BITBUCKET_COMMIT.zip,bundleType=zip
              --file-exists-behavior OVERWRITE
          - aws deploy wait deployment-successful --deployment-id $(aws deploy list-deployments
              --application-name $CODEDEPLOY_APP
              --deployment-group-name $CODEDEPLOY_GROUP_STAGING
              --query 'deployments[0]' --output text)

    - step: &ec2-deploy-production
        name: Deploy to EC2 (Production)
        deployment: production
        trigger: manual
        script:
          - zip -r deploy.zip . -x "*.git*" "node_modules/.cache/*" "__pycache__/*"
          - aws s3 cp deploy.zip s3://$S3_ARTIFACT_BUCKET/${projectName}/production/$BITBUCKET_COMMIT.zip
          - aws deploy create-deployment
              --application-name $CODEDEPLOY_APP
              --deployment-group-name $CODEDEPLOY_GROUP_PROD
              --s3-location bucket=$S3_ARTIFACT_BUCKET,key=${projectName}/production/$BITBUCKET_COMMIT.zip,bundleType=zip
              --file-exists-behavior OVERWRITE`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // S3 + CLOUDFRONT STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  if (isS3Cf && isNode && !hasCdk && !hasTf) {
    parts.push(
`
    - step: &s3-deploy-staging
        name: Deploy to S3 (Staging)
        deployment: staging
        script:
          - pipe: atlassian/aws-s3-deploy:1.6.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              S3_BUCKET: $S3_BUCKET_STAGING
              LOCAL_PATH: dist/
              DELETE_FLAG: 'true'
          - pipe: atlassian/aws-cloudfront-invalidate:1.0.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              DISTRIBUTION_ID: $CLOUDFRONT_DIST_STAGING

    - step: &s3-deploy-production
        name: Deploy to S3 (Production)
        deployment: production
        trigger: manual
        script:
          - pipe: atlassian/aws-s3-deploy:1.6.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              S3_BUCKET: $S3_BUCKET_PROD
              LOCAL_PATH: dist/
              DELETE_FLAG: 'true'
          - pipe: atlassian/aws-cloudfront-invalidate:1.0.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              DISTRIBUTION_ID: $CLOUDFRONT_DIST_PROD`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // LAMBDA DEPLOY STEP DEFINITIONS (when no IaC)
  // ══════════════════════════════════════════════════════════════════════════

  if (isLambdaInfra && !hasCdk && !hasSam && !hasTf) {
    const pkgImage = isPython ? `python:${pythonVer}-slim` : isNode ? `node:${nodeVer}-slim` : `maven:3.9-eclipse-temurin-${javaVer}`;
    const pkgScript = isPython
      ? `          - pip install -r requirements.txt -t ./package/
          - cp -r *.py ./package/
          - cd package && zip -r ../function.zip . && cd ..`
      : isNode
      ? `          - npm ci
          - zip -r function.zip . -x "*.git*" "node_modules/.cache/*"`
      : `          - mvn package -DskipTests -q
          - cp target/*.jar function.zip`;

    parts.push(
`
    - step: &package-lambda
        name: Package Lambda
        image: ${pkgImage}
        script:
${pkgScript}
        artifacts:
          - function.zip

    - step: &lambda-deploy-staging
        name: Deploy Lambda (Staging)
        deployment: staging
        script:
          - pipe: atlassian/aws-lambda-deploy:1.10.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              FUNCTION_NAME: $LAMBDA_FUNCTION_STAGING
              ZIP_FILE: function.zip

    - step: &lambda-deploy-production
        name: Deploy Lambda (Production)
        deployment: production
        trigger: manual
        script:
          - pipe: atlassian/aws-lambda-deploy:1.10.0
            variables:
              AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
              AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
              AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
              FUNCTION_NAME: $LAMBDA_FUNCTION_PROD
              ZIP_FILE: function.zip`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // CLOUDFORMATION STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  if (hasCfn) {
    parts.push(
`
    - step: &cfn-deploy-staging
        name: CloudFormation Deploy (Staging)
        image: amazon/aws-cli:latest
        deployment: staging
        script:
          - aws cloudformation deploy
              --template-file devops/cloudformation/template.yaml
              --stack-name ${projectName}-staging
              --parameter-overrides Environment=staging
              --capabilities CAPABILITY_IAM CAPABILITY_NAMED_IAM
              --no-fail-on-empty-changeset
          - aws cloudformation wait stack-update-complete --stack-name ${projectName}-staging || true

    - step: &cfn-deploy-production
        name: CloudFormation Deploy (Production)
        image: amazon/aws-cli:latest
        deployment: production
        trigger: manual
        script:
          - aws cloudformation deploy
              --template-file devops/cloudformation/template.yaml
              --stack-name ${projectName}-production
              --parameter-overrides Environment=production
              --capabilities CAPABILITY_IAM CAPABILITY_NAMED_IAM
              --no-fail-on-empty-changeset
          - aws cloudformation wait stack-update-complete --stack-name ${projectName}-production || true`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // PULUMI STEP DEFINITIONS
  // ══════════════════════════════════════════════════════════════════════════

  if (hasPulumiPy || hasPulumiTs) {
    const pulumiImage = hasPulumiTs ? `node:20-slim` : `python:${pythonVer}-slim`;
    const pulumiInstall = hasPulumiTs
      ? `          - npm install -g pulumi
          - cd devops/pulumi && npm ci`
      : `          - pip install pulumi pulumi-aws
          - cd devops/pulumi && pip install -r requirements.txt`;

    parts.push(
`
    - step: &pulumi-preview
        name: Pulumi Preview
        image: ${pulumiImage}
        script:
          - curl -fsSL https://get.pulumi.com | sh
          - export PATH=$PATH:~/.pulumi/bin
${pulumiInstall}
          - pulumi preview --stack staging

    - step: &pulumi-up-staging
        name: Pulumi Up (Staging)
        image: ${pulumiImage}
        deployment: staging
        script:
          - curl -fsSL https://get.pulumi.com | sh
          - export PATH=$PATH:~/.pulumi/bin
${pulumiInstall}
          - pulumi up --yes --stack staging

    - step: &pulumi-up-production
        name: Pulumi Up (Production)
        image: ${pulumiImage}
        deployment: production
        trigger: manual
        script:
          - curl -fsSL https://get.pulumi.com | sh
          - export PATH=$PATH:~/.pulumi/bin
${pulumiInstall}
          - pulumi up --yes --stack production`
    );
  }

  // ── Load Test Step Definition ───────────────────────────────────────────
  parts.push(
`
    - step: &load-test
        name: Load Test (Staging)
        image: grafana/k6:latest
        script:
          - k6 run tests/load-test.js --vus 10 --duration 60s --env TARGET_URL=$STAGING_URL || true`
  );

  // ── Feature: security / quality step definitions ──────────────────────────
  const secDefs = bitbucketSecurityStepDefs(feat);
  if (secDefs) parts.push(secDefs);

  const secretDef = bitbucketSecretDetectionStepDef(feat);
  if (secretDef) parts.push(secretDef);

  const containerDef = bitbucketContainerScanStepDef(feat);
  if (containerDef) parts.push(containerDef);

  const dastDef = bitbucketDastStepDef(feat);
  if (dastDef) parts.push(dastDef);

  const sonarDef = bitbucketSonarCloudStepDef(feat);
  if (sonarDef) parts.push(sonarDef);

  const infracostDef = bitbucketInfracostStepDef(feat);
  if (infracostDef) parts.push(infracostDef);

  const teamsDef = bitbucketMsTeamsStepDef(feat);
  if (teamsDef) parts.push(teamsDef);

  const smokeDef = bitbucketSmokeTestStepDef(feat);
  if (smokeDef) parts.push(smokeDef);

  const releaseDef = bitbucketReleaseAutoStepDef(feat);
  if (releaseDef) parts.push(releaseDef);

  // ── Feature: AI code review step definition ───────────────────────────────
  const aiDef = bitbucketAiReviewStepDef(feat);
  if (aiDef) parts.push(aiDef);

  // ══════════════════════════════════════════════════════════════════════════
  // PIPELINES
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`
pipelines:`);

  // ══════════════════════════════════════════════════════════════════════════
  // DEFAULT PIPELINE (PR / feature branches)
  // ══════════════════════════════════════════════════════════════════════════

  const testStep = isPython ? 'test-python' : isJava ? 'test-java' : isNode ? 'test-node' : isDotnet ? 'test-dotnet' : null;

  parts.push(`
  # ════════════════════════════════════════════════════════════════════════════
  # DEFAULT — runs on all branches (PRs, feature branches)
  # ════════════════════════════════════════════════════════════════════════════

  default:`);

  if (testStep) {
    parts.push(`    - step: *${testStep}`);
  }

  if (hasCdk) {
    parts.push(`    - step: *cdk-synth`);
  }
  if (hasTf) {
    parts.push(`    - step: *terraform-validate`);
  }
  if (hasCfn) {
    // CloudFormation validation via cfn-lint (lightweight check on feature branches)
    parts.push(`    - step:
        name: Validate CloudFormation Template
        image: cfnlint/cfn-python-lint:latest
        script:
          - cfn-lint devops/cloudformation/template.yaml || true`);
  }
  if (hasPulumiPy || hasPulumiTs) {
    parts.push(`    - step: *pulumi-preview`);
  }

  // Fallback: if nothing matched, emit a no-op so the pipeline is valid YAML
  if (!testStep && !hasCdk && !hasTf && !hasCfn && !(hasPulumiPy || hasPulumiTs)) {
    parts.push(`    - step:
        name: Validate
        script:
          - echo "No test or IaC steps configured — select a Project Type or IaC tool."`);
  }

  // Feature steps in default pipeline (security scans on all branches)
  const defFeatureSteps = bitbucketDefaultFeatureSteps(feat);
  if (defFeatureSteps) parts.push(defFeatureSteps);

  const secretStep = feat.hasSecretDetection ? `    - step: *secret-detection` : '';
  if (secretStep) parts.push(secretStep);

  const sonarStep = feat.hasSonarCloud ? `    - step: *sonarcloud` : '';
  if (sonarStep) parts.push(sonarStep);

  // ══════════════════════════════════════════════════════════════════════════
  // MAIN BRANCH PIPELINE
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`
  # ════════════════════════════════════════════════════════════════════════════
  # MAIN BRANCH — full staging → production pipeline
  # ════════════════════════════════════════════════════════════════════════════

  branches:
    main:`);

  // Test
  if (testStep) {
    parts.push(`      - step: *${testStep}`);
  }

  // Build
  if (needsDocker) {
    parts.push(`      - step: *build-docker`);
  }
  if (isNode && (isS3Cf || isMfe) && !needsDocker) {
    parts.push(`      - step: *build-node`);
  }

  // CDK Pipeline
  if (hasCdk) {
    parts.push(`      - step: *cdk-synth`);
    parts.push(`      - step: *cdk-deploy-staging`);
    if (isEcs) {
      parts.push(`      - step:
          name: Reload Staging ECS
          script:
            - pipe: atlassian/aws-ecs-deploy:2.2.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                CLUSTER_NAME: $ECS_CLUSTER_STAGING
                SERVICE_NAME: $ECS_SERVICE_STAGING
                FORCE_NEW_DEPLOYMENT: 'true'`);
    }
    if (isEks) {
      parts.push(`      - step:
          name: Helm Upgrade Staging
          image: amazon/aws-cli:latest
          script:
            - aws eks update-kubeconfig --name $EKS_CLUSTER_NAME --region $AWS_DEFAULT_REGION
            - helm upgrade --install ${appName}-staging ./helm/${appName}
                --namespace \${K8S_NAMESPACE:-default}
                --set environment=staging
                --set image.tag=$BITBUCKET_COMMIT
                --wait --timeout 5m`);
    }
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *cdk-deploy-production`);
    if (isEcs) {
      parts.push(`      - step:
          name: Reload Production ECS
          deployment: production
          script:
            - pipe: atlassian/aws-ecs-deploy:2.2.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                CLUSTER_NAME: $ECS_CLUSTER_PROD
                SERVICE_NAME: $ECS_SERVICE_PROD
                FORCE_NEW_DEPLOYMENT: 'true'`);
    }
    if (isEks) {
      parts.push(`      - step:
          name: Helm Upgrade Production
          image: amazon/aws-cli:latest
          deployment: production
          script:
            - aws eks update-kubeconfig --name $EKS_CLUSTER_NAME --region $AWS_DEFAULT_REGION
            - helm upgrade --install ${appName}-production ./helm/${appName}
                --namespace \${K8S_NAMESPACE:-production}
                --set environment=production
                --set image.tag=$BITBUCKET_COMMIT
                --wait --timeout 5m`);
    }
  }

  // Terraform Pipeline
  if (hasTf) {
    parts.push(`      - step: *terraform-validate`);
    parts.push(`      - step: *terraform-plan-staging`);
    parts.push(`      - step: *terraform-apply-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *terraform-plan-production`);
    parts.push(`      - step: *terraform-apply-production`);
  }

  // SAM Pipeline
  if (hasSam) {
    parts.push(`      - step: *sam-build`);
    parts.push(`      - step: *sam-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *sam-deploy-production`);
  }

  // ECS without IaC
  if (isEcs && !hasCdk && !hasTf) {
    parts.push(`      - step: *ecs-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *ecs-deploy-production`);
  }

  // EKS without IaC
  if (isEks && !hasCdk && !hasTf) {
    parts.push(`      - step: *eks-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *eks-deploy-production`);
  }

  // K8s-EC2 without IaC
  if (isK8sEc2 && !hasCdk && !hasTf) {
    parts.push(`      - step: *k8s-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *k8s-deploy-production`);
  }

  // S3 + CloudFront without IaC
  if (isS3Cf && isNode && !hasCdk && !hasTf) {
    parts.push(`      - step: *s3-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *s3-deploy-production`);
  }

  // Lambda without IaC
  if (isLambdaInfra && !hasCdk && !hasSam && !hasTf) {
    parts.push(`      - step: *package-lambda`);
    parts.push(`      - step: *lambda-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *lambda-deploy-production`);
  }

  // EC2 CodeDeploy without IaC
  if (isEc2 && !hasCdk && !hasTf) {
    parts.push(`      - step: *ec2-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *ec2-deploy-production`);
  }

  // CloudFormation IaC
  if (hasCfn) {
    parts.push(`      - step: *cfn-deploy-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *cfn-deploy-production`);
  }

  // Pulumi IaC
  if (hasPulumiPy || hasPulumiTs) {
    parts.push(`      - step: *pulumi-preview`);
    parts.push(`      - step: *pulumi-up-staging`);
    parts.push(`      - step: *load-test`);
    parts.push(`      - step: *pulumi-up-production`);
  }

  // Fallback: ensure main pipeline always has at least one step
  const hasMainSteps = testStep || needsDocker || hasCdk || hasTf || hasSam || isEcs || isEks ||
    isK8sEc2 || (isS3Cf && isNode) || isLambdaInfra || isEc2 || hasCfn || hasPulumiPy || hasPulumiTs;
  if (!hasMainSteps) {
    parts.push(`      - step:
          name: No deployment configured
          script:
            - echo "No deployment steps configured — select an IaC tool or Infrastructure target."`);
  }

  // Feature steps in main branch pipeline (security scans + Slack at end)
  const mainFeatureSteps = bitbucketMainFeatureSteps(feat);
  if (mainFeatureSteps) parts.push(mainFeatureSteps);

  const slackStep = bitbucketSlackMainStep(feat);
  if (slackStep) parts.push(slackStep);

  const teamsStep = bitbucketMsTeamsMainStep(feat);
  if (teamsStep) parts.push(teamsStep);

  // Feature: AI review runs on PRs
  const aiStep = bitbucketAiReviewPipelineStep(feat);
  if (aiStep) parts.push(aiStep);

  // Smoke tests after deploy steps
  const smokeStagingStep = bitbucketSmokeTestStagingStep(feat);
  if (smokeStagingStep) parts.push(smokeStagingStep);

  const smokeProductionStep = bitbucketSmokeTestProductionStep(feat);
  if (smokeProductionStep) parts.push(smokeProductionStep);

  // Release automation runs last on main
  const releaseStep = bitbucketReleaseAutoMainStep(feat);
  if (releaseStep) parts.push(releaseStep);

  // ══════════════════════════════════════════════════════════════════════════
  // CUSTOM PIPELINES (manual triggers)
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`
  # ════════════════════════════════════════════════════════════════════════════
  # CUSTOM PIPELINES — manual triggers
  # ════════════════════════════════════════════════════════════════════════════

  custom:
    # Rollback staging to previous CloudFormation state
    rollback-staging:
      - step:
          name: Rollback Staging
          script:
            - pipe: atlassian/aws-cloudformation-deploy:0.21.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                STACK_NAME: ${projectName}Stack-staging
                COMMAND: rollback-stack

    # Rollback production to previous CloudFormation state
    rollback-production:
      - step:
          name: Rollback Production
          deployment: production
          trigger: manual
          script:
            - pipe: atlassian/aws-cloudformation-deploy:0.21.0
              variables:
                AWS_ACCESS_KEY_ID: $AWS_ACCESS_KEY_ID
                AWS_SECRET_ACCESS_KEY: $AWS_SECRET_ACCESS_KEY
                AWS_DEFAULT_REGION: $AWS_DEFAULT_REGION
                STACK_NAME: ${projectName}Stack-production
                COMMAND: rollback-stack`);

  // Terraform destroy
  if (hasTf) {
    parts.push(`

    # Terraform destroy (dangerous!)
    terraform-destroy:
      - step: *terraform-destroy`);
  }

  return parts.join('\n');
}

