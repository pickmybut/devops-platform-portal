function generateBuildspecLoadTest({ projectName }) {
  return `# ──────────────────────────────────────────────────────────────────────────────
# AWS CodeBuild — buildspec-load-test.yml
# ${projectName} — k6 Load Testing
# ──────────────────────────────────────────────────────────────────────────────

version: 0.2

env:
  variables:
    TARGET_URL: ""

phases:
  install:
    commands:
      - echo "Installing k6..."
      - curl -fsSL https://github.com/grafana/k6/releases/download/v0.50.0/k6-v0.50.0-linux-amd64.tar.gz -o k6.tar.gz
      - tar -xzf k6.tar.gz
      - mv k6-v0.50.0-linux-amd64/k6 /usr/local/bin/

  build:
    commands:
      - echo "Running load test against $TARGET_URL..."
      - |
        if [ -f "tests/load-test.js" ]; then
          k6 run tests/load-test.js --vus 10 --duration 60s --env TARGET_URL=$TARGET_URL --out json=k6-results.json || true
        else
          echo "No load test file found at tests/load-test.js, creating basic test..."
          cat > /tmp/basic-load-test.js << 'EOF'
          import http from 'k6/http';
          import { check, sleep } from 'k6';
          
          export const options = {
            vus: 10,
            duration: '60s',
            thresholds: {
              http_req_duration: ['p(95)<500'],
              http_req_failed: ['rate<0.1'],
            },
          };
          
          export default function () {
            const res = http.get(__ENV.TARGET_URL);
            check(res, {
              'status is 200': (r) => r.status === 200,
              'response time < 500ms': (r) => r.timings.duration < 500,
            });
            sleep(1);
          }
        EOF
          k6 run /tmp/basic-load-test.js --env TARGET_URL=$TARGET_URL --out json=k6-results.json || true
        fi

  post_build:
    commands:
      - echo "Load test completed"

reports:
  k6-report:
    files:
      - 'k6-results.json'
    discard-paths: yes

artifacts:
  files:
    - k6-results.json
  discard-paths: yes`;
}

