/**
 * Basic Pipeline — AWS CodePipeline + CodeBuild generator.
 *
 * Full pipeline with staging/production stages, manual approvals, and rollbacks.
 *
 * Generates:
 *   - buildspec.yml for CodeBuild (test + build)
 *   - buildspec-deploy-staging.yml for staging deployment
 *   - buildspec-deploy-prod.yml for production deployment
 *   - pipeline.json for CodePipeline (CloudFormation-style definition)
 *
 * Composes build + deploy stages based on:
 *   projectType     — what language / framework is being used
 *   iac             — what infrastructure tool will be deployed
 *   projectTypeConfig — version + database choices
 */

// ═══════════════════════════════════════════════════════════════════════════════
// BUILDSPEC — Test & Build
// ═══════════════════════════════════════════════════════════════════════════════

function generateBuildspec({ projectName, appName, projectType, iac, infra, projectTypeConfig }) {
  const ptId   = projectType?.id ?? null;
  const iacId  = iac?.id         ?? 'none';
  const infraId= infra?.id       ?? 'none';
  const cfg    = projectTypeConfig ?? {};

  // ── Project-type flags ──────────────────────────────────────────────────
  const isDjango      = ptId === 'django-api';
  const isFastApi     = ptId === 'fastapi';
  const isLambdaPy    = ptId === 'python-lambda';
  const isServerless  = ptId === 'serverless';
  const isPythonApp   = isDjango || isFastApi;
  const isPython      = isPythonApp || isLambdaPy || isServerless;
  const isJava        = ptId === 'java-spring' || ptId === 'java-lambda';
  const isMfe         = ptId === 'react-mfe' || ptId === 'react-shell';
  const isNodeApi     = ptId === 'nodejs-api';
  const isNodeLambda  = ptId === 'nodejs-lambda';
  const isNode        = isMfe || isNodeApi || isNodeLambda;
  const isDotnet      = ptId === 'dotnet-api';

  // ── IaC flags ───────────────────────────────────────────────────────────
  const hasCdk      = iacId === 'python-cdk' || iacId === 'typescript-cdk' || iacId === 'csharp-cdk';
  const hasTf       = iacId === 'terraform';
  const hasSam      = iacId === 'sam';

  // ── Infra flags ─────────────────────────────────────────────────────────
  const isEcs         = infraId === 'ecs-fargate' || infraId === 'ecs-ec2';
  const isLambdaInfra = infraId === 'lambda';
  const isS3Cf        = infraId === 's3-cloudfront';
  const needsDocker   = isEcs;

  // ── Config values ───────────────────────────────────────────────────────
  const pythonVer  = cfg.pythonVersion  ?? '3.14';
  const javaVer    = cfg.javaVersion    ?? '21';
  const nodeVer    = cfg.nodeVersion    ?? '26';
  const dotnetVer  = cfg.dotnetVersion  ?? '8.0';

  const parts = [];

  // ── Header ──────────────────────────────────────────────────────────────
  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# AWS CodeBuild — buildspec.yml (Test & Build)
# ${projectName}
# Generated by the DevOps Self-Service Portal
#
# Project type : ${projectType?.name  ?? 'None'}
# IaC          : ${iac && iacId !== 'none' ? iac.name : 'None'}
# Infra        : ${infra && infraId !== 'none' ? infra.name : 'None'}
# ──────────────────────────────────────────────────────────────────────────────

version: 0.2

env:
  variables:
    AWS_DEFAULT_REGION: eu-west-2${needsDocker ? `
    ECR_REPO: ${appName}` : ''}
  exported-variables:
    - IMAGE_TAG
    - ECR_URI`
  );

  // ── Phases ──────────────────────────────────────────────────────────────

  parts.push(`
phases:`);

  // ── Install phase ───────────────────────────────────────────────────────
  const runtimeVersions = [];
  const installCmds = [];

  if (isPython) {
    runtimeVersions.push(`      python: ${pythonVer.replace('.', '')}`);
    installCmds.push(`      - echo "Setting up Python ${pythonVer}"`);
    installCmds.push(`      - pip install --upgrade pip`);
  }
  if (isJava) {
    runtimeVersions.push(`      java: corretto${javaVer}`);
    installCmds.push(`      - echo "Using Java ${javaVer}"`);
  }
  if (isNode) {
    runtimeVersions.push(`      nodejs: ${nodeVer}`);
    installCmds.push(`      - echo "Setting up Node.js ${nodeVer}"`);
  }
  if (isDotnet) {
    runtimeVersions.push(`      dotnet: ${dotnetVer}`);
    installCmds.push(`      - echo "Using .NET ${dotnetVer}"`);
  }
  if (hasCdk) {
    installCmds.push(`      - npm install -g aws-cdk`);
  }
  if (hasTf) {
    installCmds.push(`      - curl -fsSL https://releases.hashicorp.com/terraform/1.9.0/terraform_1.9.0_linux_amd64.zip -o tf.zip`);
    installCmds.push(`      - unzip -o tf.zip && mv terraform /usr/local/bin/`);
  }

  parts.push(
`  install:
    runtime-versions:
${runtimeVersions.join('\n')}
    commands:
${installCmds.join('\n')}`
  );

  // ── Pre-build phase ─────────────────────────────────────────────────────
  const preBuildCmds = [];

  if (isPython) {
    preBuildCmds.push(`      - pip install -r requirements.txt`);
  }
  if (isNode) {
    preBuildCmds.push(`      - npm ci`);
  }
  if (isDotnet) {
    preBuildCmds.push(`      - dotnet restore`);
  }
  if (needsDocker) {
    preBuildCmds.push(`      - echo "Logging in to ECR..."`);
    preBuildCmds.push(`      - aws ecr get-login-password --region $AWS_DEFAULT_REGION | docker login --username AWS --password-stdin $AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com`);
    preBuildCmds.push(`      - export IMAGE_TAG=$CODEBUILD_RESOLVED_SOURCE_VERSION`);
    preBuildCmds.push(`      - export ECR_URI=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com/$ECR_REPO`);
  }

  if (preBuildCmds.length > 0) {
    parts.push(
`  pre_build:
    commands:
${preBuildCmds.join('\n')}`
    );
  }

  // ── Build phase ─────────────────────────────────────────────────────────
  const buildCmds = [];

  // Tests
  if (isPython) {
    buildCmds.push(`      - echo "Running tests..."`);
    buildCmds.push(`      - pip install pytest pytest-cov ruff`);
    buildCmds.push(`      - ruff check . || true`);
    buildCmds.push(`      - pytest --cov=. --cov-report=xml -v || true`);
  }
  if (isJava) {
    buildCmds.push(`      - echo "Running Maven build..."`);
    buildCmds.push(`      - mvn test -q`);
    buildCmds.push(`      - mvn package -DskipTests -q`);
  }
  if (isNode) {
    buildCmds.push(`      - echo "Running tests..."`);
    buildCmds.push(`      - npm run lint || true`);
    buildCmds.push(`      - npm test || true`);
    buildCmds.push(`      - npm run build`);
  }
  if (isDotnet) {
    buildCmds.push(`      - echo "Running tests..."`);
    buildCmds.push(`      - dotnet test --no-restore`);
    buildCmds.push(`      - dotnet publish -c Release -o out`);
  }

  // Docker build
  if (needsDocker) {
    buildCmds.push(`      - echo "Building Docker image..."`);
    buildCmds.push(`      - docker build -t $ECR_URI:$IMAGE_TAG .`);
    buildCmds.push(`      - docker push $ECR_URI:$IMAGE_TAG`);
    buildCmds.push(`      - printf '[{"name":"${appName}","imageUri":"%s"}]' $ECR_URI:$IMAGE_TAG > imagedefinitions.json`);
  }

  // CDK synth
  if (hasCdk) {
    const cdkDir = 'devops/cdk';
    if (iacId === 'python-cdk') {
      buildCmds.push(`      - echo "CDK synth..."`);
      buildCmds.push(`      - cd ${cdkDir} && pip install -r requirements.txt && cdk synth`);
    } else {
      buildCmds.push(`      - echo "CDK synth..."`);
      buildCmds.push(`      - cd ${cdkDir} && npm ci && cdk synth`);
    }
  }

  // Terraform plan
  if (hasTf) {
    buildCmds.push(`      - echo "Terraform validate..."`);
    buildCmds.push(`      - cd devops/terraform && terraform init && terraform validate`);
  }

  // SAM build
  if (hasSam) {
    buildCmds.push(`      - echo "SAM build..."`);
    buildCmds.push(`      - sam build`);
  }

  // Lambda package (when no CDK/SAM)
  if (isLambdaInfra && !hasCdk && !hasSam) {
    if (isPython) {
      buildCmds.push(`      - echo "Packaging Lambda..."`);
      buildCmds.push(`      - pip install -r requirements.txt -t ./package/`);
      buildCmds.push(`      - cp -r *.py ./package/`);
      buildCmds.push(`      - cd package && zip -r ../function.zip .`);
    } else if (isNode) {
      buildCmds.push(`      - echo "Packaging Lambda..."`);
      buildCmds.push(`      - zip -r function.zip dist/ node_modules/ -x "node_modules/.cache/*"`);
    }
  }

  parts.push(
`  build:
    commands:
${buildCmds.join('\n')}`
  );

  // ── Post-build phase ────────────────────────────────────────────────────
  parts.push(
`  post_build:
    commands:
      - echo "Build completed on $(date)"`
  );

  // ── Artifacts ───────────────────────────────────────────────────────────
  const artifacts = ['    - "**/*"'];

  parts.push(
`
artifacts:
  files:
${artifacts.join('\n')}
  discard-paths: no`
  );

  // ── Cache ───────────────────────────────────────────────────────────────
  const cachePaths = [];
  if (isPython) cachePaths.push(`    - '/root/.cache/pip/**/*'`);
  if (isNode)   cachePaths.push(`    - 'node_modules/**/*'`);
  if (isJava)   cachePaths.push(`    - '/root/.m2/**/*'`);

  if (cachePaths.length > 0) {
    parts.push(
`
cache:
  paths:
${cachePaths.join('\n')}`
    );
  }

  // ── Reports ─────────────────────────────────────────────────────────────
  if (isPython || isJava || isNode) {
    parts.push(
`
reports:
  coverage:
    files:
      - '${isPython ? 'coverage.xml' : isJava ? 'target/site/jacoco/jacoco.xml' : 'coverage/cobertura-coverage.xml'}'
    file-format: ${isPython || isNode ? 'COBERTURAXML' : 'JACOCOXML'}`
    );
  }

  return parts.join('\n');
}

