// BUILDSPEC — Deploy Staging
// ═══════════════════════════════════════════════════════════════════════════════

function generateBuildspecDeployStaging({ projectName, appName, projectType, iac, infra, projectTypeConfig }) {
  const iacId   = iac?.id   ?? 'none';
  const infraId = infra?.id ?? 'none';
  const cfg     = projectTypeConfig ?? {};

  const hasPyCdk    = iacId === 'python-cdk';
  const hasTsCdk    = iacId === 'typescript-cdk';
  const hasCdk      = hasPyCdk || hasTsCdk || iacId === 'csharp-cdk';
  const hasTf       = iacId === 'terraform';
  const hasSam      = iacId === 'sam';

  const isEcs       = infraId === 'ecs-fargate' || infraId === 'ecs-ec2';
  const isS3Cf      = infraId === 's3-cloudfront';
  const isLambda    = infraId === 'lambda';

  const pythonVer   = cfg.pythonVersion ?? '3.14';

  const parts = [];

  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# AWS CodeBuild — buildspec-deploy-staging.yml
# ${projectName} — Deploy to Staging
# ──────────────────────────────────────────────────────────────────────────────

version: 0.2

env:
  variables:
    ENVIRONMENT: staging
    AWS_DEFAULT_REGION: eu-west-2

phases:
  install:
    commands:`);

  if (hasCdk) {
    parts.push(`      - npm install -g aws-cdk`);
    if (hasPyCdk) {
      parts.push(`      - pip install -r devops/cdk/requirements.txt`);
    }
  }
  if (hasTf) {
    parts.push(`      - curl -fsSL https://releases.hashicorp.com/terraform/1.9.0/terraform_1.9.0_linux_amd64.zip -o tf.zip && unzip -o tf.zip && mv terraform /usr/local/bin/`);
  }
  if (hasSam) {
    parts.push(`      - pip install aws-sam-cli`);
  }

  parts.push(`
  build:
    commands:
      - echo "Deploying to STAGING environment..."`);

  if (hasCdk) {
    parts.push(`      - cd devops/cdk && cdk deploy --require-approval never --context environment=staging --context imageTag=$IMAGE_TAG`);
  }
  if (hasTf) {
    parts.push(`      - cd devops/terraform && terraform init && terraform apply -var="environment=staging" -auto-approve`);
  }
  if (hasSam) {
    parts.push(`      - sam deploy --no-confirm-changeset --no-fail-on-empty-changeset --stack-name ${projectName}-staging --parameter-overrides Environment=staging --capabilities CAPABILITY_IAM`);
  }
  if (isEcs && !hasCdk && !hasTf) {
    parts.push(`      - aws ecs update-service --cluster $ECS_CLUSTER_STAGING --service $ECS_SERVICE_STAGING --force-new-deployment`);
    parts.push(`      - aws ecs wait services-stable --cluster $ECS_CLUSTER_STAGING --services $ECS_SERVICE_STAGING`);
  }
  if (isS3Cf && !hasCdk && !hasTf) {
    parts.push(`      - aws s3 sync dist/ s3://$S3_BUCKET_STAGING --delete`);
    parts.push(`      - aws cloudfront create-invalidation --distribution-id $CLOUDFRONT_DIST_STAGING --paths "/*"`);
  }
  if (isLambda && !hasCdk && !hasSam && !hasTf) {
    parts.push(`      - aws lambda update-function-code --function-name $LAMBDA_FUNCTION_STAGING --zip-file fileb://function.zip`);
    parts.push(`      - aws lambda wait function-updated --function-name $LAMBDA_FUNCTION_STAGING`);
  }

  parts.push(`
  post_build:
    commands:
      - echo "Staging deployment completed on $(date)"`);

  return parts.join('\n');
}

