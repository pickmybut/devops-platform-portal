/**
 * Basic Pipeline — AWS CodePipeline + CodeBuild generator.
 *
 * Generates:
 *   - buildspec.yml for CodeBuild
 *   - pipeline.json for CodePipeline (CloudFormation-style)
 *
 * Composes build + deploy stages based on:
 *   projectType     — what language / framework is being used
 *   iac             — what infrastructure tool will be deployed
 *   projectTypeConfig — version + database choices
 */

function generateBuildspec({ projectName, appName, projectType, iac, infra, projectTypeConfig }) {
  const ptId   = projectType?.id ?? null;
  const iacId  = iac?.id         ?? 'none';
  const infraId= infra?.id       ?? 'none';
  const cfg    = projectTypeConfig ?? {};

  // ── Project-type flags ──────────────────────────────────────────────────
  const isDjango      = ptId === 'django-api';
  const isFastApi     = ptId === 'fastapi';
  const isLambdaPy    = ptId === 'python-lambda';
  const isServerless  = ptId === 'serverless';
  const isPythonApp   = isDjango || isFastApi;
  const isPython      = isPythonApp || isLambdaPy || isServerless;
  const isJava        = ptId === 'java-spring' || ptId === 'java-lambda';
  const isMfe         = ptId === 'react-mfe' || ptId === 'react-shell';
  const isNodeApi     = ptId === 'nodejs-api';
  const isNodeLambda  = ptId === 'nodejs-lambda';
  const isNode        = isMfe || isNodeApi || isNodeLambda;
  const isDotnet      = ptId === 'dotnet-api';

  // ── IaC flags ───────────────────────────────────────────────────────────
  const hasCdk      = iacId === 'python-cdk' || iacId === 'typescript-cdk' || iacId === 'csharp-cdk';
  const hasTf       = iacId === 'terraform';
  const hasSam      = iacId === 'sam';

  // ── Infra flags ─────────────────────────────────────────────────────────
  const isEcs         = infraId === 'ecs-fargate' || infraId === 'ecs-ec2';
  const isLambdaInfra = infraId === 'lambda';
  const isS3Cf        = infraId === 's3-cloudfront';
  const needsDocker   = isEcs;

  // ── Config values ───────────────────────────────────────────────────────
  const pythonVer  = cfg.pythonVersion  ?? '3.14';
  const javaVer    = cfg.javaVersion    ?? '21';
  const nodeVer    = cfg.nodeVersion    ?? '26';
  const dotnetVer  = cfg.dotnetVersion  ?? '8.0';

  // ── Runtime image selection ─────────────────────────────────────────────
  let runtime;
  if (isPython)      runtime = `aws/codebuild/amazonlinux2-x86_64-standard:5.0`;
  else if (isJava)   runtime = `aws/codebuild/amazonlinux2-x86_64-standard:5.0`;
  else if (isNode)   runtime = `aws/codebuild/amazonlinux2-x86_64-standard:5.0`;
  else if (isDotnet) runtime = `aws/codebuild/amazonlinux2-x86_64-standard:5.0`;
  else               runtime = `aws/codebuild/amazonlinux2-x86_64-standard:5.0`;

  const parts = [];

  // ── Header ──────────────────────────────────────────────────────────────
  parts.push(
`# ──────────────────────────────────────────────────────────────────────────────
# AWS CodeBuild — buildspec.yml
# ${projectName}
# Generated by the DevOps Self-Service Portal
#
# Project type : ${projectType?.name  ?? 'None'}
# IaC          : ${iac && iacId !== 'none' ? iac.name : 'None'}
# ──────────────────────────────────────────────────────────────────────────────

version: 0.2

env:
  variables:
    AWS_DEFAULT_REGION: eu-west-2${needsDocker ? `
    ECR_REPO: ${appName}` : ''}`
  );

  // ══════════════════════════════════════════════════════════════════════════
  // PHASES
  // ══════════════════════════════════════════════════════════════════════════

  parts.push(`
phases:`);

  // ── Install phase ───────────────────────────────────────────────────────
  const installCmds = [];

  if (isPython) {
    installCmds.push(`      - echo "Setting up Python ${pythonVer}"`);
    installCmds.push(`      - pip install --upgrade pip`);
  }
  if (isJava) {
    installCmds.push(`      - echo "Using Java ${javaVer}"`);
  }
  if (isNode) {
    installCmds.push(`      - echo "Setting up Node.js ${nodeVer}"`);
    installCmds.push(`      - n ${nodeVer}`);
  }
  if (isDotnet) {
    installCmds.push(`      - echo "Using .NET ${dotnetVer}"`);
  }
  if (hasCdk) {
    installCmds.push(`      - npm install -g aws-cdk`);
  }
  if (hasTf) {
    installCmds.push(`      - curl -fsSL https://releases.hashicorp.com/terraform/1.9.0/terraform_1.9.0_linux_amd64.zip -o tf.zip`);
    installCmds.push(`      - unzip tf.zip && mv terraform /usr/local/bin/`);
  }
  if (needsDocker) {
    installCmds.push(`      - echo "Docker available via privileged mode"`);
  }

  if (installCmds.length > 0) {
    parts.push(
`  install:
    runtime-versions:${isPython ? `
      python: ${pythonVer.replace('.', '')}` : ''}${isJava ? `
      java: corretto${javaVer}` : ''}${isNode ? `
      nodejs: ${nodeVer}` : ''}${isDotnet ? `
      dotnet: ${dotnetVer}` : ''}
    commands:
${installCmds.join('\n')}`
    );
  }

  // ── Pre-build phase ─────────────────────────────────────────────────────
  const preBuildCmds = [];

  if (isPython) {
    preBuildCmds.push(`      - pip install -r requirements.txt`);
  }
  if (isNode) {
    preBuildCmds.push(`      - npm ci`);
  }
  if (isDotnet) {
    preBuildCmds.push(`      - dotnet restore`);
  }
  if (needsDocker) {
    preBuildCmds.push(`      - echo "Logging in to ECR..."`);
    preBuildCmds.push(`      - aws ecr get-login-password --region $AWS_DEFAULT_REGION | docker login --username AWS --password-stdin $AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com`);
    preBuildCmds.push(`      - export IMAGE_TAG=$CODEBUILD_RESOLVED_SOURCE_VERSION`);
    preBuildCmds.push(`      - export ECR_URI=$AWS_ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com/$ECR_REPO`);
  }

  if (preBuildCmds.length > 0) {
    parts.push(
`  pre_build:
    commands:
${preBuildCmds.join('\n')}`
    );
  }

  // ── Build phase ─────────────────────────────────────────────────────────
  const buildCmds = [];

  // Tests
  if (isPython) {
    buildCmds.push(`      - echo "Running tests..."`);
    buildCmds.push(`      - pip install pytest pytest-cov ruff`);
    buildCmds.push(`      - ruff check .`);
    buildCmds.push(`      - pytest --cov=. -v || true`);
  }
  if (isJava) {
    buildCmds.push(`      - echo "Running Maven build..."`);
    buildCmds.push(`      - mvn test -q`);
    buildCmds.push(`      - mvn package -DskipTests -q`);
  }
  if (isNode) {
    buildCmds.push(`      - echo "Running tests..."`);
    buildCmds.push(`      - npm run lint || true`);
    buildCmds.push(`      - npm test || true`);
    buildCmds.push(`      - npm run build`);
  }
  if (isDotnet) {
    buildCmds.push(`      - echo "Running tests..."`);
    buildCmds.push(`      - dotnet test --no-restore`);
    buildCmds.push(`      - dotnet publish -c Release -o out`);
  }

  // Docker build
  if (needsDocker) {
    buildCmds.push(`      - echo "Building Docker image..."`);
    buildCmds.push(`      - docker build -t $ECR_URI:$IMAGE_TAG .`);
    buildCmds.push(`      - docker push $ECR_URI:$IMAGE_TAG`);
    buildCmds.push(`      - printf '[{"name":"${appName}","imageUri":"%s"}]' $ECR_URI:$IMAGE_TAG > imagedefinitions.json`);
  }

  // CDK synth
  if (hasCdk) {
    const cdkDir = 'devops/cdk';
    if (iacId === 'python-cdk') {
      buildCmds.push(`      - echo "CDK synth..."`);
      buildCmds.push(`      - cd ${cdkDir} && pip install -r requirements.txt && cdk synth`);
    } else {
      buildCmds.push(`      - echo "CDK synth..."`);
      buildCmds.push(`      - cd ${cdkDir} && npm ci && cdk synth`);
    }
  }

  // Terraform plan
  if (hasTf) {
    buildCmds.push(`      - echo "Terraform plan..."`);
    buildCmds.push(`      - cd devops/terraform && terraform init && terraform plan -out=tfplan`);
  }

  // SAM build
  if (hasSam) {
    buildCmds.push(`      - echo "SAM build..."`);
    buildCmds.push(`      - sam build`);
  }

  // Lambda package (when no CDK/SAM)
  if (isLambdaInfra && !hasCdk && !hasSam) {
    if (isPython) {
      buildCmds.push(`      - echo "Packaging Lambda..."`);
      buildCmds.push(`      - pip install -r requirements.txt -t ./package/`);
      buildCmds.push(`      - cp -r *.py ./package/`);
      buildCmds.push(`      - cd package && zip -r ../function.zip .`);
    } else if (isNode) {
      buildCmds.push(`      - echo "Packaging Lambda..."`);
      buildCmds.push(`      - zip -r function.zip . -x "*.git*" "node_modules/*"`);
    }
  }

  // S3 sync (for static sites)
  if (isS3Cf && isNode) {
    buildCmds.push(`      - echo "Build complete, dist/ ready for S3 sync"`);
  }

  parts.push(
`  build:
    commands:
${buildCmds.join('\n')}`
  );

  // ── Post-build phase ────────────────────────────────────────────────────
  const postBuildCmds = [];

  postBuildCmds.push(`      - echo "Build completed on $(date)"`);

  if (hasTf) {
    postBuildCmds.push(`      - echo "Terraform plan saved to devops/terraform/tfplan"`);
  }

  parts.push(
`  post_build:
    commands:
${postBuildCmds.join('\n')}`
  );

  // ══════════════════════════════════════════════════════════════════════════
  // ARTIFACTS
  // ══════════════════════════════════════════════════════════════════════════

  const artifacts = [];

  if (needsDocker) {
    artifacts.push(`    - imagedefinitions.json`);
  }
  if (isNode && (isS3Cf || isMfe)) {
    artifacts.push(`    - dist/**/*`);
  }
  if (isJava) {
    artifacts.push(`    - target/*.jar`);
  }
  if (isDotnet) {
    artifacts.push(`    - out/**/*`);
  }
  if (hasCdk) {
    artifacts.push(`    - devops/cdk/cdk.out/**/*`);
  }
  if (hasTf) {
    artifacts.push(`    - devops/terraform/tfplan`);
  }
  if (hasSam) {
    artifacts.push(`    - .aws-sam/**/*`);
  }
  if (isLambdaInfra && !hasCdk && !hasSam) {
    artifacts.push(`    - function.zip`);
  }

  if (artifacts.length > 0) {
    parts.push(
`
artifacts:
  files:
${artifacts.join('\n')}`
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // CACHE
  // ══════════════════════════════════════════════════════════════════════════

  const cachePaths = [];
  if (isPython) cachePaths.push(`    - '/root/.cache/pip/**/*'`);
  if (isNode)   cachePaths.push(`    - 'node_modules/**/*'`);
  if (isJava)   cachePaths.push(`    - '/root/.m2/**/*'`);

  if (cachePaths.length > 0) {
    parts.push(
`
cache:
  paths:
${cachePaths.join('\n')}`
    );
  }

  return parts.join('\n');
}

function generatePipelineJson({ projectName, appName, infra, iac }) {
  const infraId = infra?.id ?? 'none';
  const iacId   = iac?.id   ?? 'none';

  const isEcs   = infraId === 'ecs-fargate' || infraId === 'ecs-ec2';
  const isS3Cf  = infraId === 's3-cloudfront';
  const hasCdk  = iacId === 'python-cdk' || iacId === 'typescript-cdk' || iacId === 'csharp-cdk';

  // Build deploy action based on infra
  let deployAction = '';

  if (isEcs) {
    deployAction = `
        {
          "name": "DeployToECS",
          "actionTypeId": {
            "category": "Deploy",
            "owner": "AWS",
            "provider": "ECS",
            "version": "1"
          },
          "configuration": {
            "ClusterName": "\${ECS_CLUSTER_NAME}",
            "ServiceName": "\${ECS_SERVICE_NAME}",
            "FileName": "imagedefinitions.json"
          },
          "inputArtifacts": [{ "name": "BuildOutput" }],
          "runOrder": 1
        }`;
  } else if (isS3Cf) {
    deployAction = `
        {
          "name": "DeployToS3",
          "actionTypeId": {
            "category": "Deploy",
            "owner": "AWS",
            "provider": "S3",
            "version": "1"
          },
          "configuration": {
            "BucketName": "\${S3_BUCKET_NAME}",
            "Extract": "true"
          },
          "inputArtifacts": [{ "name": "BuildOutput" }],
          "runOrder": 1
        }`;
  } else if (hasCdk) {
    deployAction = `
        {
          "name": "CDKDeploy",
          "actionTypeId": {
            "category": "Deploy",
            "owner": "AWS",
            "provider": "CloudFormation",
            "version": "1"
          },
          "configuration": {
            "ActionMode": "CREATE_UPDATE",
            "StackName": "${projectName}-stack",
            "TemplatePath": "BuildOutput::devops/cdk/cdk.out/${projectName}Stack.template.json",
            "Capabilities": "CAPABILITY_IAM,CAPABILITY_NAMED_IAM,CAPABILITY_AUTO_EXPAND"
          },
          "inputArtifacts": [{ "name": "BuildOutput" }],
          "runOrder": 1
        }`;
  } else {
    deployAction = `
        {
          "name": "ManualApproval",
          "actionTypeId": {
            "category": "Approval",
            "owner": "AWS",
            "provider": "Manual",
            "version": "1"
          },
          "configuration": {
            "CustomData": "Review the build output and approve deployment"
          },
          "runOrder": 1
        }`;
  }

  return `{
  "_comment": "AWS CodePipeline definition for ${projectName}",
  "_generated": "DevOps Self-Service Portal",

  "pipeline": {
    "name": "${projectName}-pipeline",
    "roleArn": "\${PIPELINE_ROLE_ARN}",

    "artifactStore": {
      "type": "S3",
      "location": "\${ARTIFACT_BUCKET}"
    },

    "stages": [
      {
        "name": "Source",
        "actions": [
          {
            "name": "Source",
            "actionTypeId": {
              "category": "Source",
              "owner": "AWS",
              "provider": "CodeStarSourceConnection",
              "version": "1"
            },
            "configuration": {
              "ConnectionArn": "\${CODESTAR_CONNECTION_ARN}",
              "FullRepositoryId": "\${REPO_OWNER}/${projectName}",
              "BranchName": "main",
              "OutputArtifactFormat": "CODE_ZIP"
            },
            "outputArtifacts": [{ "name": "SourceOutput" }],
            "runOrder": 1
          }
        ]
      },

      {
        "name": "Build",
        "actions": [
          {
            "name": "Build",
            "actionTypeId": {
              "category": "Build",
              "owner": "AWS",
              "provider": "CodeBuild",
              "version": "1"
            },
            "configuration": {
              "ProjectName": "${projectName}-build"
            },
            "inputArtifacts": [{ "name": "SourceOutput" }],
            "outputArtifacts": [{ "name": "BuildOutput" }],
            "runOrder": 1
          }
        ]
      },

      {
        "name": "Deploy",
        "actions": [${deployAction}
        ]
      }
    ]
  }
}`;
}

// ─────────────────────────────────────────────────────────────────────────────
// Public API
// ─────────────────────────────────────────────────────────────────────────────

export function buildBasicPipelineFiles(vars) {
  const buildspec = generateBuildspec(vars);
  const pipeline  = generatePipelineJson(vars);

  return [
    { path: 'buildspec.yml', content: buildspec },
    { path: 'pipeline.json', content: pipeline },
  ];
}

